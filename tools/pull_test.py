"""
tools/pull_test.py — запуск бота в ТЕСТОВОМ режиме "пул" (2026-10-13).

    python tools/pull_test.py          (из папки EZF; в Git Bash — именно прямой слэш)

Открывается то же окно программы, всё как обычно (Старт/Стоп, End), но бот работает циклом
"сбор тычками -> домой -> добивание у дома" (src/core/pull.py). Дом — место, где нажал Старт:
ставь персонажа туда, где стоят люди.

С 2026-10-20 пул — режим по умолчанию и в обычном запуске (python app_launcher.py) и в EZF.exe;
режим выбирает переключатель в окне программы (ui_state.json: farm_mode). Этот скрипт ставит
EZF_PULL=1 — пул принудительно, что бы ни стояло в переключателе (EZF_PULL=0 — принудительно обычный).

После теста пришли input_debug.log: строки PULL (тычки, "домой", "дома", где умер каждый моб)
и таблица ИТОГ СЕССИИ (сколько убийств в 35 м от дома).
"""
import os
import sys

os.environ["EZF_PULL"] = "1"               # ДО импорта бота: флаг читается при загрузке класса FarmBot
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, ROOT)
os.chdir(ROOT)                             # логи и конфиг — как при обычном запуске из папки проекта

import app_launcher  # noqa: E402

if __name__ == "__main__":
    print("EZF: ТЕСТОВЫЙ режим ПУЛ включён (сбор -> домой -> добивание у дома)", flush=True)
    app_launcher.main()
