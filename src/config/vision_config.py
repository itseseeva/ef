# HSV-диапазоны для фильтрации цветов интерфейса.
# Подгоняй значения через песочницу в vision_manager.py (блок __main__).
#
# Почему два диапазона для красного:
#   Красный в HSV "оборачивается" через границу 0/180.
#   Один диапазон его не поймает — нужны нижний (0–10) и верхний (170–180).
#
# Формат: [H, S, V]
#   H (Hue)        — оттенок,     0–180
#   S (Saturation) — насыщенность, 0–255
#   V (Value)      — яркость,      0–255

# --- Красный (HP-бар агрессивных мобов) ---
