# Зона расширена под конкретный скриншот игрока (F5/vision_manager.py
# песочница, 22.09.2026) — размечен прямоугольник, покрывающий всю
# видимую область охоты (73% ширины экрана x 38% высоты, Full HD),
# а не только узкую полосу у центра. OFFSET_X/Y — координаты ЛЕВОГО
# ВЕРХНЕГО угла зоны от центра экрана (см. VisionManager.build_roi:
# "left": center_x + offset_x), НЕ центра зоны.
#
# Плата за расширение (см. обсуждение): больше пикселей под HSV-порог
# каждый тик (нагрузка на 60 FPS цикл) и выше риск поймать чужого
# зверя/моба вместо реальной цели, если в ROI одновременно несколько
# похожих по цвету существ — если в vision_manager.py-песочнице рамка
# детекции скачет между разными объектами, сюда нужно возвращаться и
