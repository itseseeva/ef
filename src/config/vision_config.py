# ------------------------------------------------------------------
# Панель цели (2026-10-02): НЕ летающая полоска над головой моба, а
# ОТДЕЛЬНЫЙ элемент интерфейса (имя+уровень+замочек+бар+дистанция),
# который висит на ФИКСИРОВАННОМ месте экрана — не двигается вместе с
# мобом/камерой, появляется ТОЛЬКО когда реально есть выбранная цель.
#
# Координаты измерены программно (не на глаз!) по трём реальным
# скриншотам игрока на Full HD (1920x1080) — во всех трёх relative-
# координаты центра бара внутри панели совпали почти пиксель в пиксель
# (~0.588 ширины, ~0.466 высоты экрана), что и подтвердило: это
# действительно фиксированная панель, а не летающий бар. OFFSET_X/Y —
# координаты ЛЕВОГО ВЕРХНЕГО угла зоны от центра экрана (та же
# семантика, что и у TARGET_HP_* выше).
#
# Зачем это ВМЕСТЕ с TARGET_HP_* выше, а не вместо: эта панель даёт
# надёжные found/hp_percent — крошечная фиксированная зона, там физически
# неоткуда взяться декорации мира (ложного кандидата не будет), но ОДИН-
# ДВА кадра без находки из-за эффекта каста/частиц поверх неё — это
# нормальный шум захвата, не "цели нет"; см. PANEL_MISS_DEBOUNCE_FRAMES
# ниже, который именно это фильтрует. Панель НЕ даёт координаты, куда
# доворачивать камеру (не привязана к положению моба на экране). Поэтому
# TARGET_HP_* (летающий бар над головой) остаётся — но ТОЛЬКО для
# offset_x/offset_y прицеливания, а не для решения "жива ли цель".
