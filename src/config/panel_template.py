# --- Текст HP на панели ("1 647/1 647") --------------------------------------
# 2026-10-03. Цифры нарисованы поверх заливки полоски СВЕТЛО-СЕРЫМ, почти
# белым цветом (насыщенность низкая, яркость высокая), а сама заливка —
# насыщенная золотая/красная. Поэтому текст отделяется от фона простой
# пороговой маской "мало насыщенный И яркий" — она НЕ зависит от того, что
# нарисовано за панелью (мир крутится под ней), и от того, сколько HP осталось.
# Проверено на трёх разных кадрах одной цели (трава днём, ночное море, полный
# скриншот): маска совпала ПИКСЕЛЬ В ПИКСЕЛЬ (0 отличающихся), а у другой цели
# (1 949/1 949 вместо 1 647/1 647) отличается на 91 px.
#
# Размеры при Full HD: глифы 9 px высотой и ~6 px шириной, "1 647/1 647" занимает
