"""
src/config/panel_template.py

Геометрия и цвета НАСТОЯЩЕЙ панели цели Throne and Liberty (2026-10-02).

Зачем отдельный файл, а не vision_config.py: vision_config.py калибруешь
руками (HSV, офсеты ROI) — здесь же "отпечаток" интерфейса игры, измеренный
по пикселям реальных скриншотов панели (две разные цели, "Клювозавр-
молотоглав" и "Краснопёрый клювозавр" — рамка и кнопка X совпали ПИКСЕЛЬ В
ПИКСЕЛЬ). Эти числа меняются только если игра перерисует интерфейс или ты
сменишь разрешение/масштаб UI, поэтому им не место среди чисел "подгони
в песочнице".

Все размеры — в пикселях ROI панели (vision_config.TARGET_PANEL_*) при
Full HD. Другое разрешение/масштаб UI -> эти числа надо снять заново
(скриншот панели -> смотри раскладку ниже).

РАСКЛАДКА ПАНЕЛИ (строки сверху вниз, y — относительно верхней чёрной линии
рамки полоски, "T"):

    T-2, T-1   бежевая окантовка рамки (золотисто-серая, R > G > B)
    T          ЧЁРНАЯ линия рамки, тянется на ~142 px (с крошечным разрывом)
    T+1..T+10  внутренность полоски: заливка HP (жёлтая/красная) + текст
               "1 647/1 647" поверх неё
    T+11       ЧЁРНАЯ нижняя линия рамки (ровно на 11 px ниже верхней)
    T+12, T+13 бежевая окантовка снизу

    По горизонтали (x относительно ПРАВОГО конца чёрных линий "R"):
    R          вертикальная чёрная граница полоски
    R+6        левый край кнопки X
    R+8..R+19  внутренность кнопки X: тёмно-малиновая плашка (R~90, G,B~30)
               с серым крестиком X посередине

Почему именно такая схема, а не "найди жёлтый прямоугольник": жёлтый/
красный в игровом мире (трава, цветы, шерсть мобов) бывает где угодно, и
старый детектор считал панелью любую такую полоску -> бот "видел цель" на
пустой траве и бил воздух. Рамка из двух чёрных линий ровно в 11 px друг от
друга + бежевая окантовка + малиновая кнопка X одновременно — в природе
такого сочетания нет.
"""

# --- Чёрные линии рамки ---------------------------------------------------
# Пиксель считается "чёрным", если ВСЕ три канала <= этого значения. У
# настоящей рамки (11, 10, 10); у тёмного леса/тени фон обычно >= 30.
FRAME_DARK_MAX = 24

# Расстояние между верхней и нижней чёрной линиями (px) и допуск на него.
FRAME_LINE_GAP = 11
FRAME_LINE_GAP_TOL = 1

# Допустимая длина линий (px). Настоящая ~142. Широкий коридор — чтобы
# не ломаться от пары пикселей из-за масштаба, но не пускать мусор.
FRAME_SPAN_MIN = 110
FRAME_SPAN_MAX = 175

# Какая доля пикселей между концами линии должна быть чёрной (в рамке есть
# крошечный разрыв-насечка, поэтому не 1.0).
FRAME_LINE_FILL_MIN = 0.90

# Разрыв внутри линии, который ещё считаем "той же линией" (px).
FRAME_LINE_MAX_GAP = 4
# Кусок линии на КРАЮ короче этого, отделённый разрывом, — тёмный мир за торцом
# рамки, а не сама рамка (см. panel_detector._trim_edge_runs).
FRAME_EDGE_RUN_MIN = 5

# Вертикальная чёрная граница справа: доля тёмных пикселей в колонке R.
FRAME_RIGHT_EDGE_MIN = 0.70
# Правая граница рамки темнее фона, но не всегда "чёрная": на скриншоте 2026-10-04
# (список целей открыт) она 29-34 по max-каналу, а линии рамки 16-19. Ищем её в 0-2 px
# правее конца линий (торец полоски бывает на 1 px дальше) с отдельным порогом.
FRAME_EDGE_DARK_MAX = 45
FRAME_EDGE_SEARCH_PX = 2

# --- Бежевая окантовка ----------------------------------------------------
# Пиксель "бежевый": R > G > B и R - B не меньше порога, R в диапазоне.
# У настоящей окантовки (B,G,R) = (93,119,144), (79,95,119), (58,68,86).
# Трава (G > R) и небо/вода (B > R) отсекаются сразу.
#
# Порог R - B снижен с 20 до 14 (2026-10-02, панель перенесена влево, на
# тёмный ночной фон): окантовка полупрозрачная и подмешивает цвет фона, нижняя
# внешняя строка там даёт (B,G,R) = (69,75,86) -> R - B = 17, и при пороге 20
# панель отвергалась ("нет бежевой окантовки снизу"). Запас: 17 против 14.
# Ложных срабатываний это не добавляет: остальные признаки рамки (две чёрные
# линии на расстоянии 11 px, правая граница, кнопка X) остаются обязательными,
# а порядок R > G > B по-прежнему отсекает траву и синий фон.
BEIGE_MIN_R_MINUS_B = 14
# Нижний порог R снижен с 70 до 45 (2026-10-03, лог 12:54): внутренняя нижняя строка
# окантовки НЕПРОЗРАЧНАЯ и на новом месте панели всегда (B,G,R) = (50,56,69) — во всех
# 28 кадрах чёрного ящика, на любом фоне. R = 69 не дотягивал до 70 на ОДНУ единицу,
# и выбранная цель "пропадала" прямо в бою (бот ждал 4 с, потом жал Tab и терял моба).
# Запас: 69 против 45. Внутренняя верхняя строка — (79,95,119) во всех сессиях.
BEIGE_MIN_R = 45
BEIGE_MAX_R = 220
# Окантовка = полоса из BEIGE_ROWS строк сверху и снизу от чёрных линий. Доля
# столбцов полосы, где бежевая ХОТЯ БЫ ОДНА строка, должна быть >= BEIGE_FRACTION_MIN.
# Обе строки полупрозрачные: на светлом синем фоне ломается внешняя, на тёмном камне
# внутренняя (кадры чёрного ящика 2026-10-03 12:29: внутренняя нижняя (50,56,69) BGR,
# доля 0.36; внешняя 1.0). Требовать каждую строку = терять выбранную цель.
BEIGE_ROWS = 2
BEIGE_FRACTION_MIN = 0.75

# --- Кнопка X (тёмно-малиновая плашка) ------------------------------------
# Смещения внутренности плашки от правого конца линий рамки (R) по X.
PLATE_DX_FROM = 8
PLATE_DX_TO = 19          # включительно
# Строки внутренности плашки: от T+1 до T+10 включительно.
PLATE_DY_FROM = 1
PLATE_DY_TO = 10

# "Малиновый" пиксель плашки: R в диапазоне, G и B малы, R заметно больше
# обоих. У настоящей (B,G,R) = (33,29,92) ... (23,18,95).
PLATE_R_MIN = 40
PLATE_R_MAX = 130
PLATE_GB_MAX = 55
PLATE_R_OVER_GB = 1.8
# Доля малиновых пикселей в плашке (крестик X занимает ~30% -> реально ~0.7).
PLATE_CRIMSON_MIN = 0.50

# "Светлый" пиксель крестика X (серо-бежевый, ярче плашки).
PLATE_GLYPH_MIN_CHANNEL = 55
PLATE_GLYPH_MIN_PIXELS = 5

# Минимум доступных колонок плашки внутри ROI. Если ROI панели обрезает
# кнопку сильнее, плашку проверить нечем — см. PanelResult.plate_checked.
PLATE_MIN_COLUMNS = 6

# --- Заливка HP -----------------------------------------------------------
# Заливка начинается на FILL_LEFT_PAD px правее левого конца линий (L) и
# в полном HP заканчивается на FILL_RIGHT_PAD px левее правого конца (R).
FILL_LEFT_PAD = 1
FILL_RIGHT_PAD = 2
# Колонка считается "залитой", если в ней >= столько жёлтых/красных
# пикселей (текст HP затирает часть строк, но верхняя строка всегда чиста).
FILL_MIN_ROWS = 2
# Разрыв в заливке, который не считаем концом полоски (px): текст и
# насечка на рамке.
FILL_MAX_GAP = 4

# --- Цвет заливки HP в МИРЕ (летающие бары над мобами) ----------------------
# Баг (скриншот песочницы, 2026-10-02): на пустой траве мировой детектор
# "находил" цель — жёлтый диапазон из vision_config (H 15-45, S >= 100,
# V >= 100) захватывает ещё и жёлто-зелёную траву, а форма (плотность,
# соотношение сторон) у пятнышек травы бывает как у полоски. Замер по
# скриншотам игрока, СРЕДНИЕ значения HSV по пикселям компоненты
# (H 0-180, S и V 0-255):
#
#     настоящая заливка бара (мир и панель): H ~21     S ~198    V ~197
#     "кандидаты" на траве и сухой земле:    H 36-42   S 98-121  V 100-143
#
# Заливка — светящийся элемент интерфейса: насыщенная и яркая. Трава —
# тусклая. Поэтому кандидат принимается, только если СРЕДНИЕ S и V его
# пикселей не ниже этих порогов (запас: у бара ~200, у травы <= ~145).
# Среднее, а не порог на каждый пиксель — края бара смешаны с рамкой и
# темнее, но среднее по бару остаётся высоким.
# Красный бар (если он есть) тоже должен быть насыщенным и ярким; если
# красные бары перестанут находиться — смотри эти числа первыми.
WORLD_BAR_MIN_MEAN_S = 150
WORLD_BAR_MIN_MEAN_V = 160

# --- Метка ВЫБРАННОЙ цели над мобом в мире (красные стрелки) ------------------
# Табличка выбранной (Tab-ом/кликом) цели в мире нарисована иначе, чем у
# остальных мобов: по бокам имени — две красные стрелки-«ромбики», сверху
# золотая «ножка»-указатель. У невыбранных мобов — простое имя без стрелок.
# Это единственный надёжный способ понять, КАКОЙ из нескольких баров в кадре
# принадлежит цели из панели (HP у соседних мобов часто одинаковые, 100%).
# Замер по скриншоту игрока (Full HD), каждая стрелка: ~18-20 x 21 px,
# площадь ~130 px, цвет H~5, S~205, V~185; обе стрелки на одной высоте,
# примерно на 18 px выше центра бара; середина между стрелками лежит над
# серединой ПОЛНОЙ полоски (~44 px правее левого края заливки).
#
# Измерено по ОДНОМУ кадру и по сжатому скриншоту — допуски намеренно
# широкие. Если у твоих целей метка выглядит иначе (элитные мобы, боссы),
# песочница (клавиша 'm') покажет, какие бары признаны выбранными.
MARK_RED_LOWER_1 = (0, 140, 110)
MARK_RED_UPPER_1 = (10, 255, 255)
MARK_RED_LOWER_2 = (170, 140, 110)
MARK_RED_UPPER_2 = (180, 255, 255)

# Размер одной стрелки: площадь пикселей и габариты рамки (px).
MARK_MIN_AREA = 40
MARK_MAX_AREA = 400
MARK_MIN_SIDE_PX = 8
MARK_MAX_SIDE_PX = 40

# Где искать стрелки относительно бара: полоса НАД баром (px от верха бара)
