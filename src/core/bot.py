    def _make_movement(self) -> "MovementController | None":
        """Контроллер движения, если включён и есть модель (tools/build_movement_model.py)."""
        if not self._MOVE_ENABLED:
            return None
        phrases = load_phrases()
        if phrases is None:
            logger.warning("Движение выключено: нет src/config/movement_model.json — "
                           "запусти tools/build_movement_model.py после записи tools/record_movement.py")
            return None
        turns = load_turns()
        logger.info("Движение: %d фраз и %d жестов поворота из записи игрока", len(phrases), len(turns))
        return MovementController(self.input_manager, phrases, turns=turns, hold_stats=load_hold_stats())

    def _movement_on(self) -> bool:
        return self._MOVE_ENABLED and getattr(self, "movement", None) is not None

    def _movement_mode(self) -> str:
        """
        Чем сейчас заняты ноги (зовётся каждый тик, чистая функция от состояния FSM):
          - бой: урон уже идёт или добежали до моба (<=5 м) -> боевые шаги/стрейфы;
          - бой, но ещё бежим к цели -> approach: персонаж бежит сам (клик по списку / ПКМ),
            WASD оборвали бы этот бег; можно только Shift (далеко) и поворот камеры;
          - поиск: клик по списку (LIST) и подход по ПКМ (APPROACH) -> стоим по той же
            причине; остальное время поиска — ходим.
        """
        if not self._MOVE_ENABLED:
            return MODE_OFF
        if self.state is State.COMBAT:
            if not self._MOVE_IN_COMBAT:
                return MODE_OFF
            if getattr(self, "_engaged", False) or getattr(self, "_lp_in_melee", False):
                d = self._target_dist_m()
                if d is not None and d > self._COMBAT_MOVE_MAX_M:
                    return MODE_APPROACH           # моб ещё далеко — WASD оборвали бы бег к нему
                return MODE_COMBAT
            return MODE_APPROACH
        phase = getattr(self, "_search_phase", None)
        if phase is SearchPhase.LIST:
            return MODE_SELECT if self._select_strafe_ok() else MODE_OFF
        if phase is SearchPhase.APPROACH:
            return MODE_OFF
        if phase is SearchPhase.ROAM:
            nav = getattr(self, "navigator", None)
            # Без живого одометра прогулка вслепую увела бы далеко — тогда просто "живём" на месте.
            return MODE_ROAM if nav is not None and nav.available(time.monotonic()) else MODE_SEARCH
        return MODE_SEARCH

    def _list_click(self, x: float, y: float) -> None:
        """
        Alt+ПКМ по строке списка. Со стрейфом, пока курсор едет к строке (ввод сам зажмёт A/D
        до Alt и отпустит перед кнопкой мыши), если ввод это умеет (заглушки тестов — нет).
        """
        if self._SELECT_STRAFE_ENABLED and getattr(type(self.input_manager), "CLICK_STRAFE_SUPPORTED", False):
            self.input_manager.click_at(x, y, button="right", strafe=True)
        else:
            self.input_manager.click_at(x, y, button="right")

    def _select_strafe_ok(self) -> bool:
        """Фаза LIST: стрейфим, пока клик по строке ещё не нажат (потом персонаж бежит сам)."""
        if not self._SELECT_STRAFE_ENABLED:
            return False
        if not getattr(self, "_list_clicked", False):
            return True
        pressed = self._clicks_pressed()
        target = getattr(self, "_list_click_press_target", None)
        return pressed is not None and target is not None and pressed < target

    def _clicks_pressed(self) -> "int | None":
        """Счётчик нажатых кликов ввода (None — ввод его не ведёт: заглушки тестов/песочницы)."""
        v = getattr(self.input_manager, "clicks_pressed", None)
        return v if isinstance(v, int) else None

    def _movement_tick(self) -> None:
        mv = getattr(self, "movement", None)
        if mv is not None:
            mode = self._movement_mode()
            mv.set_mode(mode)
            if hasattr(mv, "set_sprint"):
                mv.set_sprint(mode == MODE_APPROACH and self._SPRINT_ENABLED and self._want_sprint())

    def _want_sprint(self) -> bool:
        """Цель из списка дальше _SPRINT_START_M — бежим в шифте; ближе _SPRINT_STOP_M — нет."""
        tl = getattr(self, "_list_last", None)
        sel = tl.selected_row if tl is not None and tl.visible else None
        d = sel.distance_m if sel is not None else None
        on = getattr(self, "_sprint_on", False)
        if d is not None:
            if not on and d > self._SPRINT_START_M:
                on = True
                gamepad_debug_logger.debug("SPRINT  цель в %d м — бегу в шифте", d)
            elif on and d <= self._SPRINT_STOP_M:
                on = False
                gamepad_debug_logger.debug("SPRINT  цель в %d м — шифт отпускаю", d)
        self._sprint_on = on
        return on

    # --- Навигация и прогулка (src/core/navigation.py) ---

    def _nav_tick(self) -> None:
        """Одометр миникарты ~5 раз/с, строка NAV в лог раз в 5 с, редкие образцы карты."""
        nav = getattr(self, "navigator", None)
        fn = getattr(self.vision, "get_minimap", None)
        if nav is None or fn is None:
            return
        now = time.monotonic()
        if now < getattr(self, "_nav_next_at", 0.0):
            return
        self._nav_next_at = now + nav.t.odo_every_s
        frame = fn()
        yaw_fn = getattr(self.input_manager, "camera_yaw_counts", None)
        nav.update(frame, now, yaw=yaw_fn() if yaw_fn is not None else None)
        mv = getattr(self, "movement", None)
        if mv is not None and getattr(mv, "moving_since", None) is not None:
            # Жмём WASD — по сдвигу карты уточняем, куда смотрит камера (нужно камере в подходе).
            nav.estimate_heading(now, mv.body_delta(nav.t.heading_window_s, now), turning=mv.turn_active)
        if now >= getattr(self, "_nav_log_at", 0.0):
            self._nav_log_at = now + self._NAV_LOG_EVERY_S
            gamepad_debug_logger.debug("NAV     %s | карта %s (%.2f)", nav.summary(),
                                       "читается" if nav.odo.ok else "НЕ читается", nav.odo.response)
        self._save_minimap_sample(frame, now)

    def _save_minimap_sample(self, frame, now: float) -> None:
        if frame is None or now < getattr(self, "_mm_sample_at", 0.0):
            return
        n = getattr(self, "_mm_samples", 0)
        writer = getattr(getattr(self, "_hp_collector", None), "writer", None)
        if writer is None or n >= self._MINIMAP_SAMPLES_MAX:
            return
        self._mm_sample_at = now + self._MINIMAP_SAMPLE_EVERY_S
        self._mm_samples = n + 1
        path = os.path.join(_PROJECT_ROOT, "minimap_samples", "mm_%02d.png" % self._mm_samples)
        writer.submit(_imwrite, path, frame.copy())

    def _roam_ready(self, now: float) -> bool:
        nav, mv = getattr(self, "navigator", None), getattr(self, "movement", None)
        return (self._ROAM_ENABLED and nav is not None and mv is not None and nav.available(now)
                and self._list_drives())

    def _enter_roam(self, now: float, why: str) -> None:
        nav = self.navigator
        self.input_manager.stop_scan()
        self.input_manager.stop_sweep()
        self.input_manager.clear_aim_target()
        wp = nav.pick_waypoint()
        self._set_phase(SearchPhase.ROAM, now, why)
        gamepad_debug_logger.debug("ROAM    прогулка: точка (%.0f, %.0f), до неё %.0f м | %s",
                                   wp[0], wp[1], nav.dist_waypoint_m(), nav.summary())

    def _search_roam(self, now: float) -> None:
        """
        Прогулка. Ноги — MovementController (режим roam: бег вперёд фразами из записи),
        здесь — куда: доворот камеры к точке, новая точка по прибытии, выход из
        застревания. Точки — вокруг места последнего убийства (якорь); цели из списка
        берём сразу.
        """
        nav, mv = self.navigator, self.movement
        if not self._roam_ready(now):
            self._set_phase(SearchPhase.TAB, now, "прогулка невозможна: нет одометра/списка/движения")
            return
        if self._try_list_target(now, "прогулка"):
            return
        if nav.is_stuck(now, mv.moving_since, mv.body_delta(nav.t.stuck_window_s, now), turning=mv.turn_active):
            mv.unstuck()
            deg = random.uniform(70.0, 150.0) * random.choice((-1.0, 1.0))
            mv.request_turn(nav.turn_counts(deg))
            nav.pick_waypoint()
            gamepad_debug_logger.debug("STUCK   застрял (карта не двигается) — назад, вбок с прыжком, поворот %+.0f°", deg)
            return
        heading = nav.estimate_heading(now, mv.body_delta(nav.t.heading_window_s, now), turning=mv.turn_active)
        if nav.arrived():
            wp = nav.pick_waypoint()
            gamepad_debug_logger.debug("ROAM    дошёл — новая точка (%.0f, %.0f), %.0f м", wp[0], wp[1], nav.dist_waypoint_m())
        if heading is None or mv.turn_active:
            return
        counts = nav.steer(now, heading)
        if counts is not None and mv.request_turn(counts):
            gamepad_debug_logger.debug("ROAM    курс %.0f°, до точки %.0f м — поворот %+.0f счётчиков",
                                       heading, nav.dist_waypoint_m(), counts)

    def _tick_zoom(self, now: float) -> None:
        """
        Раз в _ZOOM_EVERY_S — колесо вниз (первый раз до упора, потом подкрутка): камера
        на максимальном отдалении, видно больше мобов. Зовётся в осмотре (SCAN) и пока
        персонаж бежит к цели (урона ещё нет); в бою с уроном — нет: прокрутка встала бы
        в очередь перед скиллами и срезала урон. Только при свободной очереди ввода: прокрутка
        не вклинивается в Tab/подход. Время следующей прокрутки живёт между поисками
        (getattr: в тестах и песочнице бот создаётся без __init__).
        """
        if not self._ZOOM_ENABLED or now < getattr(self, "_next_zoom_at", 0.0):
            return
        if not self.input_manager.is_idle():
            return
        if self.state is State.SEARCH and self._list_has_target(now):
            return                                # в списке есть кого кликнуть — колесо подождёт (не задерживать клик)
        # Первая прокрутка за запуск — до упора, потом короткие подкрутки (см. _ZOOM_*).
        first = not getattr(self, "_zoomed_once", False)
        self._zoomed_once = True
        notches = random.randint(*(self._ZOOM_FIRST_NOTCHES if first else self._ZOOM_NOTCHES))
        self._next_zoom_at = now + random.uniform(*self._ZOOM_EVERY_S)
        gamepad_debug_logger.debug("ZOOM    колесо вниз x%d (следующая прокрутка через %.0f с)",
                                   notches, self._next_zoom_at - now)
        self.input_manager.zoom_out(notches)

    # --- Клики выбора: ПКМ только когда под прицелом выбранная цель ---

    def _crosshair_target(self) -> str:
        """
        "marked" / "other" / "none" — кто под прицелом (vision.crosshair_target).
        Без мирового зрения или у зрения без этого метода (моки старых тестов) —
        "none": судить не о чем, кликаем как раньше.
        """
        if not self._USE_WORLD_VISION:
            return "none"
        fn = getattr(self.vision, "crosshair_target", None)
        return fn(self._CROSSHAIR_RADIUS_PX) if fn is not None else "none"

    def _request_select_clicks(self, now: float, why: str, delay_s: float = 0.0) -> None:
        """
        Выбрана новая цель: поставить Ctrl+ЛКМ -> ПКМ "в ожидание". Сами клики делает
        _tick_select_clicks, как только кликать безопасно (сразу, если уже так).
        До кликов скиллы заперты (_target_locked = False, см. _act_combat_rotation).
        """
        self._sel_pending = True
        self._sel_since = now
        self._sel_not_before = now + delay_s
        self._sel_why = why
        self._sel_wait_logged = False
        self._target_locked = False
        self._autoattack_engaged = False
        self._tick_select_clicks(now)

    def _tick_select_clicks(self, now: float) -> None:
        """
        Каждый тик COMBAT, пока клики выбора ждут. Под прицелом чужой моб — ждём (камера
        ведёт прицел на выбранную), до _SELECT_CLICK_TIMEOUT_S; потом сдаёмся без кликов.
        Иначе — Ctrl+ЛКМ -> ПКМ (очередь ввода строго последовательная).
        Как тестировать без игры: fsm_test.py, блок Y (фейковое зрение с cross_fn).
        """
        if not self._sel_pending or now < self._sel_not_before:
            return
        # Свой Tab ещё в очереди -> кадр показывает старую метку; ждём, пока он отработает.
        if not self.input_manager.is_idle():
            return
        target = self._crosshair_target()
        waited = now - self._sel_since
        # ПКМ выбирает того, кто под прицелом (лог 13:41:10: "под прицелом никого" —
        # а там стоял моб, чью полоску зрение не увидело, и ПКМ сменил цель). Поэтому
        # кликаем, только когда под прицелом ИМЕННО выбранная (бар с меткой).
        # Изменено: маркер из игры часто не распознается CV.
        # Если прицел на ЛЮБОМ мобе ("other" или "marked"), мы кликаем сразу!
        if target == "none" and self._USE_WORLD_VISION:
              if waited >= self._SELECT_CLICK_TIMEOUT_S:
                  self._sel_pending = False
                  self._target_locked = True
                  return
              return
        self._sel_pending = False
        gamepad_debug_logger.debug(
            "STRIKE  под прицелом выбранная цель -> ПКМ: бег к цели и удар (%s, ждал %.2f с)",
            self._sel_why, waited,
        )
        self._mark_target()
        self.input_manager.press_button("attack")
        self._autoattack_engaged = True
        # "Первый удар отдан" — дальше ротацию держит только шлагбаум (урон).
        self._target_locked = True

    # --- Чёрный ящик ---

    def _bb_observe(self, now: float, panel_info: TargetInfo) -> None:
        """
        Каждый тик (SEARCH и COMBAT): запомнить последнее показание панели,
        пополнить кольцо кадров чёрного ящика, предложить образец текста HP
        сборщику и сохранить кадр, если панель "не узнана" из-за бежевой окантовки
        (подозрение на моргание детектора — по кадрам разберём завтра). Всё дешёвое:
        сравнения и (раз в 0.1 с) копия 50 КБ; запись на диск — в другом потоке.
        """
        self._last_panel_info = panel_info
        bb, col = self._blackbox, self._hp_collector
        if bb is None and col is None:
            return
        frame = getattr(self.vision, "last_panel_frame", None)
        pres = getattr(self.vision, "last_panel_result", None)
        if bb is not None:
            bb.tick(now, frame)
            if (
                pres is not None and not pres.ok and "бежев" in pres.reason
                and now >= self._panel_miss_capture_at
            ):
                self._panel_miss_capture_at = now + self._PANEL_MISS_CAPTURE_EVERY_S
                self._bb_event(now, "panel_miss_beige", {"reason": pres.reason})
        if col is not None and pres is not None and pres.ok and pres.text is not None:
            col.offer(pres.text, pres.hp_percent, frame, pres.bar)

    def _bb_event(self, now: float, name: str, extra: "dict | None" = None) -> None:
        """Сохранить инцидент в чёрный ящик вместе с состоянием FSM; без ящика — ничего."""
        bb = self._blackbox
        if bb is None:
            return
        pi = self._last_panel_info
        info = {
            "state": self.state.name, "phase": self._search_phase.name,
            "engaged": self._engaged, "since_entry_s": round(now - self._eg_entered_at, 2),
            "chain": self._chain_inflight["name"] if self._chain_inflight else None,
            "panel_found": pi.found if pi is not None else None,
            "hp": pi.hp_percent if pi is not None else None,
            "txt": repr(pi.hp_text) if pi is not None else None,
        }
        if extra:
            info.update(extra)
        folder = bb.event(
            now, name, info,
            panel_frame=getattr(self.vision, "last_panel_frame", None),
            world_frame=getattr(self.vision, "last_world_frame", None),
        )
        if folder:
            gamepad_debug_logger.debug("BBOX    событие '%s' сохранено: %s", name, os.path.basename(folder))

    def _handle_combat(self) -> None:
        """
        COMBAT: когда таймер действия готов — идём по ротации скиллов
        (см. _act_combat_rotation), иначе просто доворачиваем прицел.
        Если таргет пропал — уходим в SEARCH, но не по ОДНОМУ пропущенному
        кадру (см. self._target_lost_since и _TARGET_LOST_GRACE_S ниже),
        а только если пропажа держится дольше грейс-периода.

        "Жива ли цель" теперь решает ПАНЕЛЬ (panel_info.found, см.
        докстринг класса про два источника зрения) — мировой бар
        (aim_info) используется только для доворота камеры, когда он сам
        виден в конкретном кадре; его временное исчезновение (моб на миг
        скрылся за деревом) больше НЕ считается сигналом смерти.

        Если цель выбрана подходом с расстояния, пока работает режим "Tab по
        дороге" (_tick_enroute): раз в 2-3 с жмём Tab -> Ctrl+ЛКМ -> ПКМ,
        чтобы по пути взять моба поближе, до первого изменения HP цели.

        LOOT намеренно нет: в игре подбор дропа автоматический, отдельного
        нажатия/состояния для этого не требуется.
        """
        panel_info = self.vision.get_panel_target_info(self._panel_roi)
        # В бою камеру ведёт только бар ВЫБРАННОЙ цели (метка-стрелки), а не
        # ближайший к прицелу: см. _COMBAT_REQUIRE_MARKER.
        aim_info = self._read_world_bar(require_marker=self._COMBAT_REQUIRE_MARKER)
        now = time.monotonic()
        self._log_vision_status(panel_info, aim_info, now)
        # Последние показания зрения нужны охраннику (_guard_allows) и чёрному ящику.
        self._last_aim_info = aim_info
        self._last_panel_info = panel_info
        self._bb_observe(now, panel_info)

        if not panel_info.found:
            # ПЕРВЫЙ кадр без панели — ещё не факт смерти. Панель куда
            # стабильнее мирового бара (фиксированная зона, не привязана
            # к положению моба), но один сбойный кадр захвата (mss)/кадр
            # посреди анимации смены цели в самой игре всё ещё возможен —
            # грейс-период остаётся дешёвой страховкой на этот случай, а
            # не основной защитой, как было раньше с мировым баром.
            # Настоящая смерть даёт found=False СТАБИЛЬНО много кадров
            # подряд (панель пропадает совсем) — грейс-период отличает эти
            # два случая по длительности пропажи, а не по одному кадру.
            if self._target_lost_since is None:
                self._target_lost_since = now
                # "Скиллы по инерции" (лог 2026-10-04 14:47:43): цель умерла, а цепочка в
                # очереди жала скиллы дальше — игра наводила их на моба под прицелом, и бот
                # ввязывался в бой с чужим мобом, который потом бросал. Панели нет — новые
                # скиллы не жмём: цепочка замораживается и доиграется, если панель вернётся.
                self._cancel_queue(now)
            self._refresh_list(now)
            grace_s = self._lost_grace_s()
            if now - self._target_lost_since < grace_s:
                # Ждём, не трогая ни ротацию, ни прицел — по свежему
                # мгновенному "офсету" несуществующего бара (0,0) камера
                # дёрнулась бы к центру ROI на пустом месте.
                return

            missing_for_s = now - self._target_lost_since
            # Убита или потеряна? Пропажа панели сама по себе — не доказательство
            # (см. _STRICT_KILL_CHECK): смотрим, куда шло HP цели.
            killed, last_hp, rate, projected = self._kill_verdict(now)
            if (
                not killed
                and self._engaged
                and missing_for_s < self._TARGET_LOST_GRACE_S + self._LOST_HOLD_S
            ):
                # ОХРАННИК: на убийство не похоже (HP не падало быстро) -> это может
                # быть моргание панели на живой цели. Tab сейчас увёл бы нас с
                # недобитого моба, поэтому ничего не нажимаем и ждём возвращения.
                if not self._lost_hold_logged:
                    self._lost_hold_logged = True
                    gamepad_debug_logger.debug(
                        "HOLD    панель пропала %.2fс, HP было %.1f%% (скорость %.1f п.п./с, прогноз %.1f%%) — "
                        "на убийство не похоже, Tab НЕ жму, жду возвращения до %.1fс",
                        missing_for_s, last_hp, rate, projected,
                        self._TARGET_LOST_GRACE_S + self._LOST_HOLD_S,
                    )
                return
            if killed:
                logger.info("COMBAT -> SEARCH: цель пропала (убита), лут автоматический.")
                if getattr(self, "navigator", None) is not None:
                    self.navigator.set_anchor()   # мобы спавнятся тут — прогулка (если понадобится) вокруг этого места
            else:
                logger.info(
                    "COMBAT -> SEARCH: цель ПОТЕРЯНА, не убита (HP было %.0f%%, прогноз %.0f%%) — ищу её же.",
                    last_hp, projected,
                )
            # Та же причина, что и у STATE-строки в _handle_search() выше —
            # но здесь ЕЩЁ важнее: именно это место чистит очередь ротации
            # (cancel_pending_actions() ниже), и единственный способ отличить
            # в логе "обвал цепочки из-за настоящей пропажи панели" от
            # "это SEARCH сам по себе спамит тот же физический комбо" —
            # увидеть ИМЕННО эту строку с реальной длительностью пропажи.
            gamepad_debug_logger.debug(
                "STATE   COMBAT -> SEARCH (панель отсутствовала %.2fс подряд, "
                "грейс-период %.2fс; последнее HP %.1f%%, скорость %.1f п.п./с, прогноз %.1f%% -> %s) "
                "-> cancel_pending_actions()",
                missing_for_s, grace_s, last_hp, rate, projected,
                "УБИТА" if killed else "ПОТЕРЯНА",
            )
            self._bb_event(now, "lost_verdict", {
                "verdict": "killed" if killed else "lost",
                "last_hp": last_hp, "rate": rate, "projected": projected,
                "missing_for_s": missing_for_s,
            })
            self.state = State.SEARCH
            # Выбрасываем ещё не начатые шаги ротации, оставшиеся в
            # очереди с момента ДО смерти цели (например, цепочка из
            # 4 скиллов, а моб умер после второго) — без этого бот
            # доигрывает их уже в пустоту, выглядит как "бьёт воздух/труп".
            # НЕ halt_immediately() — та ещё и резко обнуляет геймпад,
            # это для панической F4-остановки, не для обычного килла.
            # cut_wait: заодно рвём паузу после долгого каста (до 5 с) — иначе
            # Tab на следующего моба ждал бы её в очереди (см. _KILL_CUTS_CAST_WAIT).
            self._cancel_queue(now, cut_wait=self._KILL_CUTS_CAST_WAIT)
            # Гасим цель фонового _aim_worker — без этого он продолжил бы
            # пытаться довoрачивать камеру к последней позиции мёртвой
            # цели вплоть до следующего успешного aim_with_stick().
            self.input_manager.clear_aim_target()
            stop_sweep = getattr(self.input_manager, "stop_sweep", None)
            if stop_sweep is not None:          # плавный разворот поиска цели из списка
                stop_sweep()
            # И "память" зрения о позиции бара — см. VisionManager.
            # reset_tracking(): без сброса поиск новой цели сравнивал бы
            # кандидатов с координатами уже мёртвой цели, вместо того
            # чтобы честно взять самого широкого заново.
            self.vision.reset_tracking()
            self._target_lost_since = None
            # Новый поиск — с чистого листа: фаза TAB, счётчики, таймеры.
            self._reset_search_state(now)
            if killed:
                # Небольшая случайная пауза перед первым Tab — см. комментарий
                # к _POST_KILL_DELAY: мгновенная реакция здесь неестественна.
                self._next_action_at = now + random.uniform(*self._POST_KILL_DELAY)
            else:
                self._begin_reacquire(now, last_hp, projected)
            return

        # Панель снова видна — сбрасываем счётчик грейс-периода, даже
        # если он был запущен секунду назад: цель жива, отсчёт больше не
        # нужен. Но запоминаем, сколько она отсутствовала: достаточно долгая
        # пропажа (дольше вспышки от удара) и возвращение = цель умерла, и
        # игра взяла другую — новая цель требует нового захвата.
        lost_since = self._target_lost_since
        self._target_lost_since = None
        self._lost_hold_logged = False
        if (
            lost_since is not None
            and self._SWAP_DETECT_ENABLED
            and now - lost_since >= self._RELOCK_GAP_S
        ):
            # ОХРАННИК: HP не выросло (с допуском на шум полоски) -> это ТА ЖЕ цель,
            # просто панель моргнула; захват и ПКМ по прицелу не трогаем (в толпе
            # они могли бы выбрать другого моба). Выросло -> игра дала другого.
            same_target = (
                self._GUARD_ENABLED
                and self._engaged
                and bool(self._hp_hist)
                and panel_info.hp_percent <= self._hp_hist[-1][1] + self._CONTINUITY_TOL_PCT
            )
            if same_target:
                gamepad_debug_logger.debug(
                    "HOLD    панель вернулась через %.2fс, HP %.1f%% -> %.1f%%: та же цель, захват не трогаю",
                    now - lost_since, self._hp_hist[-1][1], panel_info.hp_percent,
                )
                self._bb_event(now, "hold_resolved", {
                    "gap_s": now - lost_since, "hp_before": self._hp_hist[-1][1],
                    "hp_after": panel_info.hp_percent,
                })
            else:
                self._lock_new_target(now, "панель пропадала %.2fс и вернулась" % (now - lost_since))
                return

        # Копим историю HP для строгой проверки убийства (см. _kill_verdict).
        self._record_hp(now, panel_info.hp_percent)

        # Список целей: видим ли нашу цель выбранной (нужно быстрому вердикту смерти).
        tl = self._refresh_list(now)
        if tl is not None and tl.visible and tl.selected_row is not None:
            self._list_saw_selected = True

        # Отложенные Ctrl+ЛКМ -> ПКМ после выбора цели (ждут, пока под прицелом не чужой).
        self._tick_select_clicks(now)

        if self._enroute_active:
            self._tick_enroute(now, panel_info)

        # Шлагбаум: первое упавшее HP = цель в зоне удара, можно кастовать.
        self._update_engagement(now, panel_info)
        if self.state is not State.COMBAT:      # шлагбаум мог бросить недостижимую цель
            return

        # Камера дальше — пока персонаж БЕЖИТ к цели (захват отдан, урона ещё нет):
        # скиллы всё равно заперты, а цель у прицела, короткая заморозка камеры
        # ничего не стоит. getattr — у тестовых ботов без __init__ поля может не быть.
        if not getattr(self, "_engaged", True) and getattr(self, "_target_locked", False):
            self._tick_zoom(now)

        # Игра могла сама взять другого моба, не выпуская нас из COMBAT.
        self._track_target_swap(now, panel_info)

        if now >= self._next_action_at:
            self._act_combat_rotation(now)

        # Цель выбрана списком: камеру не дёргаем к чему попало, а плавно ищем ИМЕННО её
        # (полоску с меткой выбора) и мягко ведём (см. _list_camera).
        if self._list_drives():
            self._tick_relock_click(now)
            self._tick_reengage(now)
            self._list_camera(now, aim_info)
            if getattr(self, "_list_saw_selected", False) and self.state is State.COMBAT:
                self._list_progress(now)
        elif aim_info.found:
            self._maybe_correct_aim(aim_info)

    def _lost_grace_s(self) -> float:
        """
        Сколько ждать возвращения пропавшей панели (см. _FAST_KILL_*). Последний
        замер HP — из _hp_hist (пишется раз в 0.1 с, пока панель видна), поэтому
        он не старше 0.1 с до пропажи. Отрицательное HP = "не знаем" -> обычный грейс.
        """
        # Список целей: строка ещё выбрана -> панель просто моргнула (свечение, эффекты),
        # ждём дольше обычного. А вот "строки нет" — НЕ смерть (лог 2026-10-04 12:26-12:28):
        # моб, с которым идёт бой, пропадает из списка "Астрального зрения" в момент
        # первого удара. Раньше это читалось как "умер" (грейс 0.3 с), и любое моргание
        # панели бросало живого моба — главная причина "бот не добивает".
        hist = self._hp_hist
        low_hp = bool(hist) and 0.0 <= hist[-1][1] <= self._FAST_KILL_MAX_HP
        tl = getattr(self, "_list_last", None) if self._LIST_TARGETING else None
        if tl is not None and tl.visible and tl.selected_row is not None and getattr(self, "_list_saw_selected", False):
            return self._FAST_KILL_GRACE_S if low_hp else self._LIST_ALIVE_GRACE_S
        if low_hp:
            return self._FAST_KILL_GRACE_S
        return self._TARGET_LOST_GRACE_S

    def _record_hp(self, now: float, hp: float) -> None:
        """
        Раз в _KILL_HP_SAMPLE_EVERY_S кладёт (время, HP панели) в скользящее
        окно. Не каждый кадр: 60 записей в секунду ничего не добавили бы к
        оценке скорости падения, а окно на 3 с хранит ровно 30 чисел.
        """
        if now >= self._hp_next_sample_at:
            self._hp_hist.append((now, hp))
            self._hp_next_sample_at = now + self._KILL_HP_SAMPLE_EVERY_S

    def _kill_verdict(self, now: float) -> "tuple[bool, float, float, float]":
        """
        Убита ли цель, пропавшая с панели. Возвращает
        (убита, последнее HP, скорость падения п.п./с, прогноз HP).

        Прогноз = последнее HP - скорость * (сколько уже нет панели, не больше
        _KILL_PROJECT_CAP_S). Скорость = (HP в начале окна - HP в конце) / длина
        окна по ВРЕМЕНИ, не меньше нуля (HP вверх = смена цели, а не лечение
        в нашу пользу) и только если в окне накопилось >= _KILL_MIN_HISTORY_S.
        Убита, если прогноз <= _KILL_MAX_PROJECTED_HP ЛИБО цель активно добивали
        (скорость >= _KILL_ACTIVE_RATE и последнее HP <= _KILL_ACTIVE_MAX_HP).

        Пустая история (панель пропала, не успев дать ни одного замера) или
        выключенная проверка -> по-старому "убита": данных против нет.

        Чистая функция от self._hp_hist и now: легко гонять в песочнице —
        подставь deque из пар (t, hp) и сравни вердикт (fsm_test.py, сценарии V).
        """
        hist = self._hp_hist
        if not self._STRICT_KILL_CHECK or not hist:
            return True, 0.0, 0.0, 0.0
        t_last, hp_last = hist[-1]
        t_first, hp_first = hist[0]
        span = t_last - t_first
        rate = max(0.0, (hp_first - hp_last) / span) if span >= self._KILL_MIN_HISTORY_S else 0.0
        horizon = min(max(0.0, now - t_last), self._KILL_PROJECT_CAP_S)
        projected = max(0.0, hp_last - rate * horizon)
        killed = (
            projected <= self._KILL_MAX_PROJECTED_HP
            or (rate >= self._KILL_ACTIVE_RATE and hp_last <= self._KILL_ACTIVE_MAX_HP)
        )
        return killed, hp_last, rate, projected

    def _track_target_swap(self, now: float, panel_info: TargetInfo) -> None:
        """
        Зовётся каждый кадр COMBAT, где панель видна. Ловит "цель сменилась,
        а мы этого не заметили": HP на панели вырос на _SWAP_HP_JUMP_PCT п.п.
        над МЕДИАНОЙ последних ~2 с и держится так _SWAP_CONFIRM_S подряд.
        Тогда — новый захват (см. _on_target_swap / _lock_new_target). Пока прыжок
        подтверждается, ротация стоит (см. _act_combat_rotation).

        Почему медиана, а не "последний кадр" или минимум: HP-бар на панели
        иногда на пару кадров читается уже/шире, чем есть (вспышка удара,
        эффект поверх). Минимум принял бы такой провал за новый "пол", и
        возвращение к норме выглядело бы как прыжок вверх. Медиана
        одиночные выбросы игнорирует, а плавное падение HP в бою просто
        сдвигает её вместе с реальным значением.

        Пока прыжок подтверждается, в историю ничего не пишем: иначе
        "новые" высокие значения подмешивались бы в эталон.
        """
        if not self._SWAP_DETECT_ENABLED:
            return

        hp = panel_info.hp_percent
        samples = self._swap_samples

        if len(samples) >= self._SWAP_MIN_SAMPLES:
            ref = statistics.median(samples)
            if hp - ref >= self._SWAP_HP_JUMP_PCT:
                if self._swap_since is None:
                    self._swap_since = now
                if now - self._swap_since >= self._SWAP_CONFIRM_S:
                    self._on_target_swap(now, ref, hp)
                return

        # Прыжка нет (или эталона ещё нет): сбрасываем подтверждение и
        # раз в _SWAP_SAMPLE_EVERY_S пополняем историю.
        self._swap_since = None
        if now >= self._swap_next_sample_at:
            samples.append(hp)
            self._swap_next_sample_at = now + self._SWAP_SAMPLE_EVERY_S

    def _on_target_swap(self, now: float, ref_hp: float, new_hp: float) -> None:
        """
        Смена цели по прыжку HP подтверждена. История HP обнуляется в любом
        случае (новый моб — новый эталон). Захват — если с прошлого прошло не
        меньше _SWAP_LOCK_MIN_GAP_S: пока идёт предыдущий (~0.85 с), второй
        подряд лишний (а если в игре Ctrl+ЛКМ — переключатель, ещё и снятие).
        """
        self._swap_samples.clear()
        self._swap_next_sample_at = now
        self._swap_since = None

        since_lock = now - self._last_lock_at
        if since_lock < self._SWAP_LOCK_MIN_GAP_S:
            gamepad_debug_logger.debug(
                "SWAP    цель сменилась (hp %.0f%% -> %.0f%%), но захват поставлен %.1fс назад (< %.1fс) — пропускаю",
                ref_hp, new_hp, since_lock, self._SWAP_LOCK_MIN_GAP_S,
            )
            return

        self._lock_new_target(now, "hp %.0f%% -> %.0f%%" % (ref_hp, new_hp))

    def _lock_new_target(self, now: float, why: str) -> None:
        """
        Игра дала другую цель, не выпуская нас из COMBAT: повторяем вход в бой
        так же, как _enter_combat — "захват -> удар", и только потом скиллы.

        cancel_pending_actions(): шаги ротации, ещё стоящие в очереди, были
        рассчитаны на СТАРУЮ цель; пусть лучше пропадут, чем отработают без
        захвата. Исполняемое сейчас не трогаем (оборвать нажатие грубее).
        """
        self._cancel_queue(now)
        self._swap_samples.clear()
        self._swap_next_sample_at = now
        self._swap_since = None
        # Новый моб: его ещё не били, шлагбаум закрывается заново, а охранник
        # снова разрешает смену цели (старый моб нам уже не важен).
        self._engage_reset(now)
        self._bb_event(now, "swap_relock", {"why": why})
        # История HP относилась к СТАРОМУ мобу: для проверки убийства нового
        # она бы только исказила скорость падения.
        self._hp_hist.clear()
        self._hp_next_sample_at = now
        self._target_locked = False     # до первого удара (ПКМ) скиллы заперты
        if self._USE_WORLD_VISION:
            # Липкий захват мирового бара остался на СТАРОЙ цели: пусть зрение
            # выберет бар заново ("ближайший к прицелу"), иначе камера
            # продолжила бы вести бар уже мёртвого моба.
            getattr(self.vision, "release_bar_lock", lambda: None)()
        if self._list_drives():
            self._relock_from_list(now, why)
            return
        gamepad_debug_logger.debug("RELOCK  новая цель (%s) -> Ctrl+ЛКМ, потом удар и скиллы", why)
        self._request_select_clicks(now, "смена цели игрой")
        self._next_action_at = now + random.uniform(*self._FIRST_STRIKE_DELAY)

    def _relock_from_list(self, now: float, why: str) -> None:
        """
        Игра сама выбрала другого моба (напал на нас / поймал скилл). Раньше бот к нему
        не бежал, "расстояние не уменьшается" -> бросал его недобитым (лог 14:47:35, 14:47:44).
        Теперь: моб далеко и есть в списке -> кликаем его строку (бег + удар), рядом или
        его нет в списке (он уже в бою с нами) -> сразу открываем ротацию и добиваем.
        """
        self._lp_best = None                      # прогресс подхода — заново, от этого моба
        self._lp_in_melee = False
        self._lp_faded_since = None
        self._target_locked = True                # Ctrl+ЛКМ / ПКМ по прицелу не нужны: цель уже выбрана
        tl = getattr(self, "_list_last", None)
        sel = tl.selected_row if tl is not None and tl.visible else None
        if sel is not None and sel.distance_m is not None and sel.distance_m > self._LP_MELEE_M:
            self._relock_click_at = now + random.uniform(*self._LIST_REACTION_S)
            gamepad_debug_logger.debug("RELOCK  игра выбрала №%d (%d м, %s) — кликаю её в списке: бегу к ней и бью",
                                       sel.index, sel.distance_m, why)
            return
        self._relock_click_at = None
        self._list_saw_selected = sel is not None
        gamepad_debug_logger.debug("RELOCK  игра выбрала моба рядом (%s) — он уже в бою с нами, добиваю", why)
        self._open_gate(now, "цель выбрана игрой, моб рядом")

    def _target_dist_m(self) -> "int | None":
        """Расстояние до НАШЕЙ цели по списку (выбранная строка) или None — строки нет/не прочли."""
        if not self._LIST_TARGETING:
            return None
        tl = getattr(self, "_list_last", None)
        sel = tl.selected_row if tl is not None and tl.visible else None
        return sel.distance_m if sel is not None else None

    def _reengage_click(self, now: float, why: str) -> bool:
        """
        Цель выбрана, но мы её не достаём: клик по её строке в списке (Alt+ПКМ) — игра снова
        ведёт персонажа к ней и бьёт. Скиллы в очереди (по недосягаемой цели) замораживаем.
        True — клик поставлен.
        """
        if now < getattr(self, "_reengage_next_at", 0.0):
            return False
        tl = getattr(self, "_list_last", None)
        sel = tl.selected_row if tl is not None and tl.visible else None
        if sel is None:
            return False
        if not self.input_manager.is_idle():
            self._cancel_queue(now)               # скиллы всё равно не долетают — не ждём конца цепочки
            return False
        jx, jy = self._LIST_JITTER_PX
        px, py = sel.click_point
        self._list_click(*self.vision.list_point_to_screen(
            (px + random.uniform(-jx, jx), py + random.uniform(-jy, jy))))
        self._reengage_next_at = now + self._REENGAGE_COOLDOWN_S
        self._reengage_since = None
        self._lp_in_melee = False
        self._eg_last_dmg_at = now                # дать время добежать, прежде чем снова решать "урона нет"
        gamepad_debug_logger.debug("REENGAGE %s — цель №%d в %s м, кликаю её в списке: подбегаю и бью",
                                   why, sel.index, "?" if sel.distance_m is None else sel.distance_m)
        return True

    def _tick_reengage(self, now: float) -> None:
        """В бою моб отошёл/мы отстали дальше _REENGAGE_DIST_M и урона нет — подбежать (см. выше)."""
        if not getattr(self, "_engaged", False):
            self._reengage_since = None
            return
        d = self._target_dist_m()
        if d is None or d <= self._REENGAGE_DIST_M:
            self._reengage_since = None
            return
        since = getattr(self, "_reengage_since", None)
        if since is None:
            self._reengage_since = now
            return
        if now - since < self._REENGAGE_CONFIRM_S:
            return
        if now - getattr(self, "_eg_last_dmg_at", now) < 1.5:
            return                                # урон идёт (дальнобойные скиллы достают) — не мешаем
        self._reengage_click(now, "моб в %d м, урона нет" % d)

    def _tick_relock_click(self, now: float) -> None:
        """Отложенный клик по строке цели, которую выбрала игра (см. _relock_from_list)."""
        at = getattr(self, "_relock_click_at", None)
        if at is None or now < at or not self.input_manager.is_idle():
            return
        self._relock_click_at = None
        tl = self._refresh_list(now)
        sel = tl.selected_row if tl is not None and tl.visible else None
        if sel is None:
            self._open_gate(now, "цель выбрана игрой, в списке её уже нет — она рядом")
            return
        jx, jy = self._LIST_JITTER_PX
        px, py = sel.click_point
        self._list_click(*self.vision.list_point_to_screen(
            (px + random.uniform(-jx, jx), py + random.uniform(-jy, jy))))
        self._list_saw_selected = True
        self._lp_best = None
        self._list_cam_search_started = now

    def _act_combat_rotation(self, now: float) -> None:
        """
        Одна попытка действия в COMBAT, когда _next_action_at уже
        разрешает действовать. Идём по self._chains В ПОРЯДКЕ СПИСКА (это
        и есть приоритет: важные цепочки — выше, см. поле "order" в
        skills_config.json) и кастуем ПЕРВУЮ, чей собственный дедлайн
        next_ready_at уже прошёл. Если ни одна не готова — обычная
        автоатака (RB), как и раньше.

        Кастуем ВСЮ цепочку одним махом — вызываем execute_combo() для
        каждого скилла цепочки подряд, без пауз между вызовами со стороны
        FSM. Это НЕ блокирует 60 FPS цикл: execute_combo() внутри
        InputManager только кладёт задачу в очередь воркера
        (queue.Queue.put — микросекунды) и сразу возвращается, а сам ввод с
        рандомизированными паузами между командами исполняется отдельным
        потоком-воркером (см. InputManager._worker) — FSM-поток тут ничем
        не рискует, даже если в цепочке 5+ скиллов подряд.

        now передаётся параметром, а не считается заново через
        time.monotonic() внутри метода — тот же принцип, что и с
        _next_action_at: один "снимок времени" на весь тик, чтобы кулдауны
        разных цепочек сравнивались с ОДНИМ и тем же моментом.

        Важная деталь (баг, найденный и подтверждённый логами
        InputManager): execute_combo() кладёт команды в очередь и сразу
        возвращается — САМИ нажатия могут физически доигрывать ещё
        несколько секунд после этого. _SKILL_CAST_DELAY ниже (0.4-0.8с) —
        это короткая пауза "не спамь ПОВЕРХ анимации", а не оценка полного
        времени цепочки. Без проверки is_idle() FSM успевала бы решить
        кастовать ДРУГУЮ цепочку (или снова эту же после её собственного
        кулдауна) ДО того, как предыдущая на самом деле доиграла —
        команды обеих цепочек сваливались в одну очередь и перемешивались
        в реальных нажатиях. is_idle() — дешёвая неблокирующая проверка,
        не завершённые задачи очереди InputManager, безопасна внутри
        60 FPS цикла.
        """
        # ЖЁСТКОЕ ПРАВИЛО: ни скиллов, ни ударов, пока цель не захвачена.
        # Все пути входа/смены цели ставят Ctrl+ЛКМ раньше (очередь ввода
        # строго последовательная), этот запрет — страховка на случай, если
        # какой-то путь про захват забыл: лучше стоять, чем бить "мимо".
        if not self._target_locked:
            if not self._gate_logged:
                self._gate_logged = True
                gamepad_debug_logger.debug(
                    "GATE    скиллы заблокированы: по цели ещё не отдан первый удар (ПКМ)"
                )
            return

        # ШЛАГБАУМ: пока HP цели ни разу не изменилось после входа в бой, мы
        # не знаем, что бьём моба, а не воздух — ротация ждёт (идёт автоатака).
        if self._ENGAGE_GATE_ENABLED and not self._engaged:
            if not self._eg_gate_logged:
                self._eg_gate_logged = True
                gamepad_debug_logger.debug(
                    "GATE    ротация ждёт первого упавшего HP цели (она ещё не в зоне удара)"
                )
            return

        # Идёт подтверждение прыжка HP (возможно, цель уже сменилась): пока
        # не ясно — скиллы не ставим, иначе они ушли бы по новой цели ДО
        # захвата. Если тревога ложная, задержка не больше _SWAP_CONFIRM_S.
        if self._swap_since is not None:
            return

        # ЖЁСТКИЙ ЗАМОК (см. _CHAIN_*): пока идёт предыдущая цепочка (или её
        # хвостовая пауза) — ни новой цепочки, ни автоатаки. _chain_busy идёт
        # ПЕРВЫМ: он же фиксирует конец цепочки (CHAIN END).
        if self._chain_busy(now):
            self._log_chain_wait(now)
            return

        # Остальное, что стоит в очереди (захват, удар, шаг) — тоже ждём.
        if not self.input_manager.is_idle():
            return

        # Сначала — скиллы цепочки, замороженной смертью прошлой цели (_CHAIN_FROZEN_MAX_S).
        if self._resume_frozen_chain(now):
            self._autoattack_engaged = False
            return

        for chain in self._chains:
            if now >= chain["next_ready_at"]:
                logger.info(
                    "COMBAT: кастую цепочку '%s' (%d скилл(ов): %s).",
                    chain["name"], len(chain["gamepad_steps"]), chain["sequence"],
                )
                # cast_times — параллельный gamepad_steps список (та же
                # длина и порядок, см. skills_config.py) с реальным временем
                # каста каждого шага или None, если у шага нет кастомного
                # времени (тогда execute_combo сам возьмёт обычную короткую
                # межскилльную паузу). zip(), а не индекс по range(len()) —
                # идиома Python для "иду по двум спискам синхронно
                # попарно", читается как сама мысль "шаг + его время каста",
                # без риска рассинхронизировать индексы вручную.
                # Замок: с этого момента цепочка "в полёте" (min_end — нижняя оценка конца).
                # Каждый скилл — с меткой: при смерти цели посреди цепочки ненажатые
                # доиграем на следующей (_freeze_inflight_chain / _resume_frozen_chain).
                self._start_chain_steps(now, chain["name"],
                                        list(zip(chain["gamepad_steps"], chain["cast_times"])))

                # Кулдаун — диапазон, разыгрываем КОНКРЕТНОЕ значение один
                # раз здесь и запоминаем как абсолютный дедлайн (тот же
                # приём, что и у _next_action_at ниже) — а не перегенерируем
                # случайное число на каждой проверке готовности, что дало бы
                # "мерцающий" кулдаун вместо стабильного значения на цикл.
                cooldown_s = random.uniform(
                    chain["cooldown_min"], chain["cooldown_max"]
                )
                chain["next_ready_at"] = now + cooldown_s
                # Каст скилла прерывает текущую автоатаку персонажа — после
                # цепочки автоатаку придётся запускать заново одним свежим
                # нажатием RB, а не полагаться на то, что она сама
                # продолжится после чужого действия поверх неё.
                self._autoattack_engaged = False
                # ВАЖНО (источник путаницы при чтении лога вручную):
                # каждая цепочка считает СВОЙ кулдаун от СВОЕГО собственного
                # предыдущего каста — независимо от других цепочек. Если
                # цепочка 2 откастовалась между двумя кастами цепочки 1,
                # это НЕ сдвигает и НЕ сбрасывает таймер цепочки 1. Поэтому
                # "цепочка 1 началась почти сразу после конца цепочки 2"
                # может быть абсолютно верным поведением — печатаем здесь
                # явный дедлайн, чтобы это было видно по секундам в логе, а
                # не приходилось прикидывать на глаз по временным меткам
                # COMBO START/END.
                gamepad_debug_logger.debug(
                    "ROTATION: цепочка '%s' кастуется, следующий повтор "
                    "через %.1fс (диапазон %.1f-%.1fс, независимо от других "
                    "цепочек).",
                    chain["name"], cooldown_s,
                    chain["cooldown_min"], chain["cooldown_max"],
                )
                # Пауза "не спамь поверх анимации" — НЕ кулдаун цепочки (тот
                # отдельно лежит в next_ready_at и продолжает тикать
                # независимо от этой паузы).
                self._next_action_at = now + random.uniform(*self._SKILL_CAST_DELAY)
                return

        # Ни одна цепочка из ротации не готова. РАНЬШЕ здесь на каждой такой
        # проверке (~раз в секунду, по _COMBAT_ATTACK_COOLDOWN) заново жалось
        # RB — а в игре одно нажатие уже запускает цикл автоатаки, который
        # крутится сам без повторных нажатий. Спам RB тут был лишним и не
        # соответствовал реальному поведению персонажа (и это лишние
        # нажатия конкретно на ту же кнопку, что уже отслеживает EAC).
        # Поэтому жмём RB ТОЛЬКО если автоатака ещё не запущена
        # (_autoattack_engaged == False) — а не готовую цепочку всё равно
        # продолжаем проверять на каждом тике, просто без лишнего нажатия.
        if not self._autoattack_engaged:
            if not self._guard_allows(now, "attack_click"):
                # ПКМ в прицел сейчас мог бы выбрать другого моба — не жмём,
                # спросим снова через обычный интервал.
                self._next_action_at = now + random.uniform(*self._COMBAT_ATTACK_COOLDOWN)
                return
            gamepad_debug_logger.debug(
                "ROTATION: ни одна цепочка не готова -> запускаю автоатаку "
                "(RB). Остаток кулдауна: %s",
                ", ".join(
                    f"'{c['name']}'={max(0.0, c['next_ready_at'] - now):.1f}с"
                    for c in self._chains
                ),
            )
            self.input_manager.press_button("attack")
            self._autoattack_engaged = True

        self._next_action_at = now + random.uniform(*self._COMBAT_ATTACK_COOLDOWN)

    def _log_chain_wait(self, now: float) -> None:
        """
        Раз в _CHAIN_WAIT_LOG_EVERY_S пишет, что замок удержал готовую цепочку:
        по этим строкам видно, что "ещё одно комбо" бот НЕ запустил, а ждал
        (60 строк в секунду утопили бы лог, поэтому троттлинг).
        """
        if now < self._chain_wait_log_at:
            return
        ready = next((c["name"] for c in self._chains if now >= c["next_ready_at"]), None)
        if ready is None:
            return
        self._chain_wait_log_at = now + self._CHAIN_WAIT_LOG_EVERY_S
        ch = self._chain_inflight
        if ch is not None:
            gamepad_debug_logger.debug(
                "CHAIN   WAIT: '%s' готова, но идёт '%s' (%.1f с из минимум %.1f с) — жду",
                ready, ch["name"], now - ch["start"], ch["min_end"] - ch["start"],
            )
        else:
            gamepad_debug_logger.debug(
                "CHAIN   WAIT: '%s' готова, хвостовая пауза после предыдущей цепочки — жду", ready
            )

    def _maybe_correct_aim(self, aim_info: TargetInfo) -> None:
        """
        Репортит СВЕЖУЮ позицию цели в InputManager — вызывается КАЖДЫЙ
        тик, когда МИРОВОЙ бар виден (aim_info.found — см. докстринг
        класса про два источника зрения; это НЕ то же самое, что "жива ли
        цель", за то отвечает панель). Раньше этот метод сам решал "пора
        ли доворачивать" (свой кулдаун _next_aim_correction_at + мёртвая
        зона) и слал aim_with_stick() как разовую команду в очередь
        InputManager — теперь это просто мгновенная запись в "почтовый
        ящик" фонового _aim_worker (см. InputManager.aim_with_stick()),
        дешёвая операция, которую можно (и нужно) звать каждый тик.
        Решение "двигать стик сейчас или ждать" (мёртвая зона, сглаживание,
        тремор, реализм) принимает уже сам _aim_worker в своём потоке —
        FSM здесь только поставляет самые свежие координаты, ничего не
        решая сама.
        """
        self.input_manager.aim_with_stick(aim_info.offset_x, aim_info.offset_y)

    def _log_vision_status(
        self, panel_info: TargetInfo, aim_info: TargetInfo, now: float
    ) -> None:
        """
        Троттлированная строка VISION в gamepad_debug.log — раз в
        _VISION_LOG_INTERVAL_S, а не каждый тик (иначе 60 строк в секунду
        утопили бы полезные AIM/COMBO записи в том же файле). Единственный
        способ УВИДЕТЬ вживую во время реального прогона (F5), что
        VisionManager реально что-то находит и какие числа считает, не
        поднимая отдельное cv2.imshow-окно (то живёт только в песочнице
        vision_manager.py).

        Печатает ОБА источника раздельно (панель — источник правды про
        found/hp, мировой бар — источник offset для прицела) — иначе по
        логу было бы не видно случаев их расхождения (см. докстринг
        класса), а это самое интересное место для отладки.
        """
        if now < self._next_vision_log_at:
            return
        self._next_vision_log_at = now + self._VISION_LOG_INTERVAL_S

        # Почему зрение НЕ признало панель ("нет малиновой плашки кнопки X",
        # "нет чёрных линий рамки"...). Без этого строка "цели нет" ничего не
        # объясняла бы: на живом прогоне нельзя отличить "цели правда нет" от
        # "панель есть, а проверка структуры её не узнаёт" (например, у боссов
        # другая рамка). getattr: у мок-зрения тестов такого поля нет.
        pres = getattr(self.vision, "last_panel_result", None)
        why = pres.reason if pres is not None else "-"

        if not self._USE_WORLD_VISION:
            # Режим "только панель": мирового бара нет, в строке только панель.
            if panel_info.found:
                gamepad_debug_logger.debug(
                    "VISION  panel: found=True hp=%.1f%%  |  world=off (только панель)", panel_info.hp_percent
                )
            else:
                gamepad_debug_logger.debug(
                    "VISION  panel: found=False (цели нет: %s)  фаза=%s  |  world=off (только панель)",
                    why, self._search_phase.name,
                )
            return

        # bars — сколько HP-баров нашло зрение в кадре, lock — держит ли оно
        # захват на одном из них (см. VisionManager._find_hp_bar).
        extra = "bars=%d marked=%d lock=%s enroute=%s eng=%s txt=%s" % (
            getattr(self.vision, "last_candidate_count", 0), getattr(self.vision, "last_marked_count", 0),
            getattr(self.vision, "bar_locked", False), self._enroute_active, self._engaged,
            ("%08x/%d" % (panel_info.hp_text.sig, panel_info.hp_text.ink)) if panel_info.hp_text else "-",
        )
        if panel_info.found:
            gamepad_debug_logger.debug(
                "VISION  panel: found=True hp=%.1f%%  |  aim: found=%s offset=(%+.1f, %+.1f)  |  %s",
                panel_info.hp_percent, aim_info.found, aim_info.offset_x, aim_info.offset_y, extra,
            )
        else:
            gamepad_debug_logger.debug(
                "VISION  panel: found=False (цели нет: %s)  фаза=%s  |  aim: found=%s offset=(%+.1f, %+.1f)  |  %s",
                why, self._search_phase.name, aim_info.found, aim_info.offset_x, aim_info.offset_y, extra,
            )


