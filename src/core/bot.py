    def run(self) -> None:
        """
        Бесконечный цикл на ~60 FPS. На каждом тике:
          1. Диспетчер вызывает обработчик текущего состояния.
          2. Обработчик сам проверяет свой таймер и сам решает, менять ли
             self.state.
          3. Цикл спит ровно столько, сколько нужно, чтобы удержать 60 FPS.
        """
        self._running = True
        logger.info("FarmBot: цикл запущен.")
        if getattr(self, "movement", None) is not None:
            self.movement.start()                 # поток один на всю жизнь бота, повторный start — пустышка
        if getattr(self, "navigator", None) is not None:
            self.navigator.set_anchor()           # прогулка — вокруг места, где бота запустили (потом — где убил)
        try:
            self._run_loop()
        finally:
            # Стоп/ошибка: движение — в "стоп" сразу, не ждать следующего тика (его не будет).
            if getattr(self, "movement", None) is not None:
                self.movement.set_mode(MODE_OFF)
                if hasattr(self.movement, "cancel_turn"):
                    self.movement.cancel_turn()

    def _run_loop(self) -> None:
        while self._running:
            frame_start = time.perf_counter()
            # Новый конфиг из приложения (request_chains_reload) применяем ЗДЕСЬ,
            # в потоке FSM, между тиками: ротация никогда не увидит полузаменённый
            # список, и кулдаун, только что выставленный кастом, не потеряется.
            pending = getattr(self, "_pending_chains", None)
            if pending is not None:
                self._pending_chains = None
                self._apply_chains(pending)

            self._nav_tick()
            handler = self._handlers[self.state]
            handler()
            self._movement_tick()

            # Вычисляем ОСТАТОК тика через perf_counter(), а не наивный
            # time.sleep(self._FRAME_TIME). Наивный вариант копит дрейф:
            # если обработка кадра заняла 5 мс, а мы всё равно спим полные
            # 16.6 мс, реальный FPS со временем плавно проседает ниже 60.
            # Здесь же мы спим ровно "то, что осталось" от бюджета тика.
            elapsed = time.perf_counter() - frame_start
            sleep_time = self._FRAME_TIME - elapsed
            if sleep_time > 0:
                time.sleep(sleep_time)
            else:
                # Кадр обработался дольше бюджета 16.6 мс — не фатально,
                # но сигнал, что где-то в state-логике узкое место
                # (например, зрение подвисло на тяжёлом кадре).
                logger.debug(
                    "FarmBot: тик превысил бюджет 60 FPS на %.1f мс",
                    -sleep_time * 1000,
                )

    def stop(self) -> None:
        """Останавливает цикл run() после текущего тика."""
        self._running = False
        if getattr(self, "movement", None) is not None:
            self.movement.set_mode(MODE_OFF)      # ноги — сразу, не через тик
            if hasattr(self.movement, "cancel_turn"):
                self.movement.cancel_turn()       # и жест камеры не доигрываем

    # ------------------------------------------------------------------
    # Обработчики состояний
    # ------------------------------------------------------------------

    # Смена цели в T&L на геймпаде (2026-10-02, подтверждено ручным
    # F7-тестом в app_launcher.py — см. историю диагностики этого дня):
    # НЕ RB+Y (это оказался слот скила 4, "Множественный выстрел", см.
    # skills_config.json), и НЕ RB+удержание стика (эффекта не дало).
    # Рабочий механизм — InputManager.flick_target(): голый короткий
    # флик правого стика, без RB. Направление — просто зафиксированная
    # сторона; T&L не различает их семантически (оба варианта — "следующая
    # цель" в одном из двух обходов списка).
    _SEARCH_FLICK_DIRECTION = "right"

    def _read_world_bar(self, require_marker: bool = False) -> TargetInfo:
        """
        Мировой HP-бар (источник offset для камеры/подхода) или заглушка
        "бара нет", если мировое зрение выключено (_USE_WORLD_VISION). Единая
        точка: ни одно место в FSM не зовёт vision.get_target_info() напрямую,
        поэтому выключатель действует везде сразу.

        require_marker=True — только бар с меткой выбранной цели (бой, см.
        _COMBAT_REQUIRE_MARKER). Флаг НЕ передаём, когда он False: так мок-
        зрение старых тестов с сигнатурой get_target_info(roi) продолжает
        работать, а лишний аргумент нужен только там, где метка действительно
        требуется.
        """
        if not self._USE_WORLD_VISION:
            return self._NO_WORLD_BAR
        if require_marker:
            return self.vision.get_target_info(self._target_roi, require_marker=True)
        if getattr(self, "_vision_switch_pending", False):
            # Бежим к мобу, которого выбрало зрение, а в игре ещё выбрана прежняя
            # цель: её бар (с меткой) не ведём, иначе камера вернулась бы к ней.
            return self.vision.get_target_info(self._target_roi, avoid_marked=True)
        return self.vision.get_target_info(self._target_roi)

    def _scan_tab_delay(self) -> float:
        """Пауза до следующего пробного Tab в фазе SCAN."""
        rng = self._SEARCH_RETRY_TAB_S if self._USE_WORLD_VISION else self._SCAN_TAB_PANEL_ONLY_S
        return random.uniform(*rng)

    def _handle_search(self) -> None:
        """
        SEARCH: ищем цель в три этапа (SearchPhase), от дешёвого к дорогому:
          1. TAB      — 2-3 нажатия Tab: берёт ближайшего моба в радиусе таргета.
          2. SCAN     — Tab не взял: камера сама водит влево-вправо, ждём бар.
          3. APPROACH — бар виден, но моб далеко: наводим камеру и жмём ПКМ,
                        персонаж бежит к мобу и бьёт.
        Почему так: Tab берёт только близких мобов, а HP-бары видны и у
        далёких — это и есть "цели рядом, но не слишком рядом для Tab".

        В режиме "только панель" (по умолчанию) мировых баров нет, поэтому
        фаза APPROACH недостижима: ищем так — Tab, затем круговой осмотр на
        360° с Tab раз в 2-3 с и шагами вперёд.

        "Нашли ли цель" на ЛЮБОМ этапе решает ПАНЕЛЬ (panel_info.found, см.
        докстринг класса) — это и есть переход в COMBAT (_enter_combat).
        Мировой бар (aim_info) нужен только для осмотра/подхода: он говорит,
        ГДЕ моб, но не "выбран ли он".
        """
        panel_info = self.vision.get_panel_target_info(self._panel_roi)
        aim_info = self._read_world_bar()
        now = time.monotonic()
        self._log_vision_status(panel_info, aim_info, now)
        self._note_tab_result(now, panel_info.found, panel_info.hp_percent)
        self._bb_observe(now, panel_info)
        # Колесо только в осмотре (никого не видно — отдаление помогает найти).
        # Раньше крутили и сразу после убийства: камера замерзала на 0.4-0.7 с ровно
        # тогда, когда надо доворачивать к следующему мобу (лог 17:35:29, 17:35:57).
        if self._search_phase in (SearchPhase.SCAN, SearchPhase.ROAM):
            self._tick_zoom(now)

        if panel_info.found and self._unreach_tab_pending:
            # Только что бросили недостижимого моба, а его панель ещё на экране:
            # сначала Tab (сменить/снять цель), и лишь потом можно верить панели —
            # иначе через 0.3 с подтверждения мы вернулись бы в бой с ним же.
            self._panel_seen_since = None
            if now >= self._next_action_at and self.input_manager.is_idle():
                self._unreach_tab_pending = False
                self._press_tab(now, "цель недостижима")
                self._next_action_at = now + random.uniform(*self._SEARCH_FLICK_COOLDOWN)
            return

        if self._search_phase is SearchPhase.LIST:
            # Панель может ещё показывать ПРЕЖНЮЮ цель (смена из боя): в бой входим
            # только по подтверждению из списка, а не по панели.
            self._search_list_wait(now, panel_info, aim_info)
            return

        if self._vision_switch_pending:
            if self._search_phase is SearchPhase.APPROACH:
                # Панель ещё показывает ПРЕЖНЮЮ цель (в игре она выбрана, пока мы
                # не кликнули нового моба) — в бой по ней не входим, бежим к новому.
                self._panel_seen_since = None
                self._search_approach(now, aim_info)
                return
            self._vision_switch_pending = False   # подход сорвался — обычный поиск

        if panel_info.found:
            if (
                self._search_phase is SearchPhase.REACQUIRE
                and not self._reacquire_hp_matches(panel_info.hp_percent)
            ):
                # Панель есть, но это ДРУГОЙ моб (HP не похоже на потерянную
                # цель): в бой не входим, подтверждение сбрасываем и жмём Tab
                # дальше по обычному ритму.
                self._panel_seen_since = None
                self._search_reacquire(now, panel_info)
                return
            if self._panel_confirmed(now):
                self._enter_combat(now, panel_info, aim_info)
            # Панель видна, но ещё не подтверждена: ничего НЕ жмём (новый Tab
            # сменил бы только что выбранную настоящую цель), а камера
            # осмотра, если она крутилась, просто продолжает крутиться —
            # она живёт в своём потоке и останавливается только в
            # _enter_combat().
            return

        self._panel_candidate_lost(now)

        if self._search_phase is SearchPhase.REACQUIRE:
            self._search_reacquire(now, panel_info)
            return

        if self._search_phase is SearchPhase.APPROACH:
            self._search_approach(now, aim_info)
            return

        if self._search_phase is SearchPhase.RECOVERY:
            self._search_recovery(now)
            return

        if self._search_phase is SearchPhase.ROAM:
            self._search_roam(now)
            return
        # Список целей — первым: игра сама знает, кто рядом и насколько далеко.
        if self._try_list_target(now, "поиск"):
            self._list_empty_since = None
            return
        if self._list_drives():
            since = getattr(self, "_list_empty_since", None)
            if since is None:
                self._list_empty_since = since = now
            if now - since >= self._ROAM_AFTER_EMPTY_S and self._roam_ready(now):
                self._list_empty_since = None
                self._enter_roam(now, "в списке никого %.0f с — иду искать" % (now - since))
                return
            # Список открыт, но кликнуть некого (пусто или все строки в чёрном списке):
            # поиск камерой не нужен — список видит мобов вокруг и без неё. Ждём.
            self.input_manager.stop_scan()
            self.input_manager.stop_sweep()
            self.input_manager.clear_aim_target()
            if not getattr(self, "_list_idle_logged", False):
                self._list_idle_logged = True
                gamepad_debug_logger.debug("LIST    кликнуть некого (пусто/чёрный список) — камеру не кручу, жду")
            return
        self._list_idle_logged = False
        if self._LIST_TARGETING and getattr(self, "_list_ever_seen", False):
            # Список целей был, а теперь не виден (закрыт / другая вкладка). Раньше бот
            # переходил на старый поиск зрением и бежал к случайному мобу в кадре
            # (жалоба 2026-10-04 "не выбирает из списка, просто бежит"). Теперь ждём список.
            self.input_manager.stop_scan()
            self.input_manager.stop_sweep()
            self.input_manager.clear_aim_target()
            if not getattr(self, "_list_gone_logged", False):
                self._list_gone_logged = True
                gamepad_debug_logger.debug("LIST    список целей не виден (закрыт или не вкладка 'Персонаж') — "
                                           "к мобам вслепую не бегу, жду список")
            return

        if self._USE_WORLD_VISION:
            self._track_bars(now, aim_info)
        if self._search_phase is SearchPhase.TAB:
            self._search_tab(now)
        else:
            self._search_scan(now)

    # --- Подтверждение панели (антидребезг входа в COMBAT) ---

    def _panel_confirmed(self, now: float) -> bool:
        """
        Зовётся на КАЖДОМ кадре, где панель найдена. True — панель держится
        непрерывно >= _PANEL_CONFIRM_S, можно входить в COMBAT.
        Разрыв между кадрами с панелью > _PANEL_GAP_S обнуляет отсчёт (см.
        _PANEL_GAP_S); разрыв в 1-2 кадра внутри уже не обнуляет — их глушит
        антидребезг самого зрения (PANEL_MISS_DEBOUNCE_FRAMES).
        """
        if (
            self._panel_seen_since is None
            or now - self._panel_last_found_at > self._PANEL_GAP_S
        ):
            self._panel_seen_since = now
            gamepad_debug_logger.debug(
                "PANEL   появилась, подтверждаем %.2fс (фаза=%s)",
                self._PANEL_CONFIRM_S, self._search_phase.name,
            )
        self._panel_last_found_at = now

        held = now - self._panel_seen_since
        if held < self._PANEL_CONFIRM_S:
            return False

        gamepad_debug_logger.debug("PANEL   подтверждена (%.2fс непрерывно)", held)
        self._panel_seen_since = None
        return True

    def _panel_candidate_lost(self, now: float) -> None:
        """
        Кадр БЕЗ панели в SEARCH: если шёл отсчёт подтверждения — это было
        ложное срабатывание (вспышка/мир в зоне панели). Пишем в лог, как
        долго оно держалось: по этим строкам подбирается _PANEL_CONFIRM_S.
        """
        if self._panel_seen_since is None:
            return
        gamepad_debug_logger.debug(
            "PANEL   ложное срабатывание: пропала через %.2fс (< %.2fс) — игнорирую",
            self._panel_last_found_at - self._panel_seen_since, self._PANEL_CONFIRM_S,
        )
        self._panel_seen_since = None

