class State(Enum):
    """
    Состояния FSM.

    Enum, а не строки/числа напрямую — идиома Python: даёт автодополнение
    в IDE, ловит опечатки на этапе разработки (сравнение State.COMBAT
    вместо магической строки "combat"), и не даёт случайно сравнить
    состояние с произвольным числом.

    auto() вместо ручных значений (1, 2, 3) — числовое значение состояния
    нигде не используется по смыслу (мы никогда не пишем State.SEARCH <
    State.COMBAT), поэтому расставлять числа руками — лишний риск
    опечататься при добавлении ESCAPE в будущем.
    """
    SEARCH = auto()
    COMBAT = auto()


class SearchPhase(Enum):
    """
    Под-фазы состояния SEARCH. Это НЕ новые состояния FSM (снаружи бот всё
    так же "ищет"), а внутренний этап поиска цели — отдельный Enum, чтобы
    не раздувать State и не ломать диспетчер состояний.

    TAB      — быстрый способ: жмём Tab 2-3 раза (выбирает ближайшую цель в
               радиусе таргета). Работает, только если моб достаточно близко.
    SCAN     — Tab ничего не дал: камера сама водит влево-вправо (осмотр),
               иногда делаем шаг вперёд и снова пробуем Tab. Ждём, пока в
               кадре появится HP-бар моба.
    APPROACH — бар моба виден, но Tab его не берёт (далеко): наводим на него
               камеру и жмём ПКМ — персонаж сам бежит к мобу и бьёт.
    REACQUIRE — цель из боя ПРОПАЛА, но не убита (HP не дошло до нуля): ищем
               ЕЁ ЖЕ Tab-ом и принимаем только панель с похожим HP, чужого
               моба не берём (см. _KILL_* / _REACQUIRE_* ниже).
    LIST     — (2026-10-04) клик Alt+ЛКМ по строке ближнего моба в списке целей
               "Астрального зрения": ждём, пока игра переставит рамку выбора на
               эту строку — это подтверждение от самой игры, что моб выбран.
    ROAM     — (2026-10-04) прогулка: в списке никого — бежим к случайной точке рядом с
               "домом" (где бот запустили), а ушли дальше поводка — домой. Где мы и куда
               смотрим — по миникарте (src/core/navigation.py).
    """
    TAB = auto()
    SCAN = auto()
    RECOVERY = auto()
    APPROACH = auto()
    REACQUIRE = auto()
    LIST = auto()
    ROAM = auto()


class FarmBot:
    """
    Главный класс бота. Владеет VisionManager и InputManager, хранит текущее
    состояние FSM и крутит realtime-цикл на ~60 FPS.

    Архитектурный принцип (неблокирующий таймер действий):
        Внутри run() НИКОГДА не вызывается time.sleep() дольше одного тика
        (~16.6 мс). Каждое состояние вместо блокирующего ожидания хранит
        метку времени self._next_action_at (time.monotonic()) — следующее
        действие выполняется только когда текущее время её обогнало.

        Благодаря этому бот способен среагировать на события 60 раз в
        секунду, а не "спит" секунду-две вслепую. Это станет критично,
        когда появится ESCAPE: опасность нужно заметить за один кадр,
        а не через секунду после блокирующего ожидания.

    ДВА ИСТОЧНИКА ЗРЕНИЯ (по умолчанию оба включены, _USE_WORLD_VISION = True):
    панель цели решает "цель есть / жива", мировой HP-бар над мобом ищет и
    ведёт цели (осмотр, подход, доворот камеры). Режим "только панель"
    (_USE_WORLD_VISION = False) оставлен как запасной: мировой бар тогда не
    читается вообще, мобов ищут Tab и круговой осмотр.

    Два источника зрения, две разные роли (2026-10-02):
        found/hp_percent (жива ли цель, сколько у неё HP — то, что решает
        переходы SEARCH<->COMBAT) теперь читаются ИЗ ПАНЕЛИ ЦЕЛИ
        (self._panel_roi, VisionManager.get_panel_target_info) — это
        фиксированный маленький элемент интерфейса, который появляется
        ТОЛЬКО когда реально есть выбранная цель, и физически не может
        зацепить декорацию мира (в отличие от широкой мировой зоны).

        offset_x/offset_y для доворота камеры по-прежнему читаются из
        летающего бара НАД ГОЛОВОЙ моба (self._target_roi,
        VisionManager.get_target_info) — панель не привязана к положению
        моба на экране, этот сигнал только она дать не может.

        Это значит: на каждом тике ДВА отдельных TargetInfo — panel_info
        (решает found/hp, см. _handle_search/_handle_combat) и aim_info
        (решает offset, см. _maybe_correct_aim). Они МОГУТ временно
        расходиться (например, aim_info.found=False на миг, пока моб
        скрыт деревом, а panel_info.found всё ещё True) — это ожидаемо и
        не баг: _maybe_correct_aim() просто пропускает коррекцию в такие
        тики, а panel_info остаётся единственным источником правды про
        "жив ли таргет".

    Довoрот камеры (геймпад):
        После перехода с Interception на виртуальный геймпад (vgamepad +
        ViGEmBus) камера крутится уже не дельтой мыши, а отклонением
        правого стика — это не позиция, а СКОРОСТЬ поворота, зависящая от
        силы отклонения и времени удержания. TargetInfo.offset_x/offset_y
        (смещение ТЕЛА моба от точки прицела игры в пикселях, из aim_info выше;
        см. src/config/aim_config.py)
        передаются в input_manager.aim_with_stick(dx, dy) как сигнал
        "насколько и в какую сторону довернуть" — перевод пикселей в силу
        и длительность удержания стика происходит уже внутри InputManager,
        FSM про это ничего не знает и знать не должна.

        С этого этапа aim_with_stick() — не команда "выполни довод", а
        мгновенное обновление позиции цели для НЕПРЕРЫВНОГО фонового
        потока камеры (InputManager._aim_worker, свой поток, отдельный от
        очереди боевых комбо). FSM здесь просто репортит зрение каждый
        тик — когда двигать стик, когда держать паузу, решает уже сам
        _aim_worker. Подробности и обоснование архитектуры — в докстринге
        класса InputManager. Единственная обязанность FSM-стороны —
        вызвать input_manager.clear_aim_target(), когда цель пропала (см.
        _handle_combat), чтобы фоновый поток не пытался доворачивать
        камеру к уже неактуальной последней позиции.
    """

    _TARGET_FPS = 60
    _FRAME_TIME = 1.0 / _TARGET_FPS

    # Кулдауны действий — диапазоны (min, max), а не фиксированное число.
    # Даже на этом простом этапе нажатие ровно раз в секунду миллисекунда
    # в миллисекунду — само по себе статистический паттерн, который EAC
    # умеет ловить анализом ритма (та же логика, что уже в
    # InputManager._AFTER_CMD_MS для пауз между командами).
    # Название не "_SEARCH_TAB_..." — старое, от давней (неверной) догадки
    # про Tab-эквивалент; переименовано при переходе на flick_target()
    # (2026-10-02), чтобы не путать читающего код про действие, которого
    # уже нет.
    _SEARCH_FLICK_COOLDOWN = (0.4, 0.6)
    _COMBAT_ATTACK_COOLDOWN = (0.9, 1.1)

    # Пауза перед первым Tab после смерти цели (переход COMBAT -> SEARCH).
    # НЕ делаем этот переход мгновенным (_next_action_at = 0.0), в отличие
    # от других переходов: реакция "труп -> Tab" за один кадр (16 мс) —
    # статистически неестественный ритм, который EAC-анализ засекает
    # быстрее, чем сами нажатия. Живой игрок хотя бы долю секунды смотрит
    # на экран, прежде чем искать следующую цель.
    _POST_KILL_DELAY = (0.05, 0.15)

    # Пауза между первым ударом (ПКМ по выбранной цели, см. _handle_search)
    # и первой цепочкой скиллов. ПКМ запускает бег к цели и автоатаку; без
    # паузы скилл улетал бы в очередь сразу следом, пока персонаж ещё
    # стоит далеко от моба (скилл не достаёт / сбивает движение). Диапазон,
    # а не константа — та же анти-детект логика, что и у остальных пауз.
    _FIRST_STRIKE_DELAY = (0.1, 0.25)

    # ---- Фазы поиска цели (SearchPhase). Все времена — диапазоны (min, max):
    # одинаковые паузы от цикла к циклу — статистический отпечаток бота. ----

    # Сколько раз подряд жать Tab в начале поиска, прежде чем сдаться и
    # перейти к осмотру/подходу. randint по этому диапазону на каждый новый
    # поиск: человек то жмёт Tab дважды, то трижды.
    _SEARCH_TAB_ATTEMPTS = (2, 3)

    # Сколько ПОДРЯД должен держаться в кадре один и тот же HP-бар, чтобы
    # мы поверили, что это моб, а не мерцание/случайный блик. Время, а не
    # число кадров: частота зрения плавает, а смысл порога — "человек тоже
    # не реагирует на то, что мелькнуло на 1 кадр".
    _SEARCH_BARS_PERSIST_S = (0.15, 0.3)

    # Фаза APPROACH. Допуск наведения (экранные px): камера считается
    # "наведённой", когда бар (с поправкой на тело моба) ближе этого к
    # центру. И сколько секунд нужно удержаться в допуске до клика —
    # человек не кликает в тот же кадр, когда прицел только дошёл.
    _APPROACH_AIM_TOL_PX = 45.0
    _APPROACH_SETTLE_S = (0.15, 0.4)

    # Бар HP висит НАД головой моба, а кликать надо по телу: поправка "бар ->
    # тело" и точка прицела игры теперь живут в src/config/aim_config.py и
    # уже учтены в aim_info.offset_x/offset_y (VisionManager.get_target_info),
    # поэтому здесь и в бою одна и та же формула наведения.

    # Сколько всего даём подходу: наведение + бег + повторы. Если за это
    # время панель цели не появилась — подход считается проваленным.
    _APPROACH_RUN_TIMEOUT_S = (9.0, 13.0)

    # Повторный клик, если после предыдущего панель так и не появилась, и
    # максимум кликов за один подход. Перед КАЖДЫМ повтором персонаж
    # делает шаг вперёд и жмёт Tab (_APPROACH_RETRY_WALK_S): если ПКМ по
    # далёкому мобу не выбирает цель, это страховка "подбежать и взять Tab-ом".
    # 2026-10-03 (скорость): было 2.5-4.0 с. По логу 17:35 панель появляется через
    # 0.2-0.3 с после удачного клика, а неудачный первый клик (моб далеко) был в 3
    # подходах из 7 — каждый стоил ~3 с ожидания впустую.
    _APPROACH_RECLICK_S = (0.8, 1.2)
    # 3 -> 5 (2026-10-03, скорость): клики теперь раз в ~1 с (см. _APPROACH_RECLICK_S),
    # и после третьего неудачного бот иначе стоял до таймаута подхода (9-13 с).
    # Перед каждым повтором — шаг вперёд, так что 5 попыток = ~5 с бега к мобу.
    _APPROACH_MAX_CLICKS = 5
    _APPROACH_RETRY_WALK_S = (0.7, 1.2)

    # Если бар пропал из кадра дольше этого (с): моб ушёл/скрылся -> назад в SCAN.
    _APPROACH_BAR_LOST_S = 1.5

    # Фаза SCAN: как часто пробовать Tab, пока водим камерой (персонаж
    # мог оказаться ближе к мобу), и "шаги вперёд", чтобы сменить место.
    _SEARCH_RETRY_TAB_S = (8.0, 12.0)
    _SCAN_WALK_ENABLED = True
    _SCAN_WALK_EVERY_S = (6.0, 12.0)
    _SCAN_WALK_DURATION_S = (0.5, 1.1)

    # Ctrl+ЛКМ УДАЛЁН из бота (2026-10-03, решение пользователя): в игре он выбирает
    # того, кто под курсором, обрывает бег к мобу, а клик в пустоту снимает цель
    # (логи 12:55, 13:16, 13:25). Цель берут только Tab и ПКМ подхода.
    #
    # ПРАВИЛО "СНАЧАЛА ПЕРВЫЙ УДАР" (COMBAT): ни одного скилла, пока по новой цели
    # не отдан первый удар (ПКМ) — флаг self._target_locked (см. _act_combat_rotation).
    #   1. Появилась цель -> ПКМ (бег и удар) -> скиллы после первого урона.
    #   2. Цель сменилась без выхода из COMBAT -> то же заново.
    # Вход SEARCH -> COMBAT (пункт 1) и после смерти цели с паузой > грейс-
    # периода (пункт 2: COMBAT -> SEARCH -> новый вход) уже проходят через
    # _enter_combat и захватывают. Остаётся случай "игра сама взяла следующего
    # моба, бот не выходил из COMBAT" — его ловим по двум признакам панели:
    #   (а) HP вырос: у одного моба в бою он только падает, прыжок вверх =
    #       другой моб. Сравниваем с МЕДИАНОЙ за окно _SWAP_REF_WINDOW_S
    #       (медиана не замечает одиночных провалов бара от вспышек) и
    #       требуем, чтобы прыжок держался _SWAP_CONFIRM_S подряд. История
    #       копится раз в _SWAP_SAMPLE_EVERY_S — это ~20 чисел, медиана
    #       считается за микросекунды и FPS не страдает.
    #   (б) панель пропадала на >= _RELOCK_GAP_S и вернулась (в пределах
    #       грейс-периода). Вспышки от ударов гасят панель на 0.36-0.41 с,
    #       поэтому порог выше этого.
    # Слепая зона: смена на моба с тем же HP без пропажи панели невидима.
    #
    # Порог прыжка 15 п.п. (был 25): по логу игра взяла нового моба при HP
    # 51% -> 100%, а над медианой падающего HP это всего +24 п.п.
    _SWAP_DETECT_ENABLED = True
    _SWAP_HP_JUMP_PCT = 15.0       # на сколько п.п. HP должен вырасти над медианой
    _SWAP_CONFIRM_S = 0.75         # сколько прыжок должен держаться подряд (увеличено для защиты от помех)
    _SWAP_REF_WINDOW_S = 2.0       # окно истории для медианы
    _SWAP_SAMPLE_EVERY_S = 0.1     # период записи в историю
    _SWAP_MIN_SAMPLES = 5          # меньше (0.5 с истории) — эталона ещё нет
    _SWAP_LOCK_MIN_GAP_S = 1.0     # захват только что поставлен (идёт ~0.85 с) — второй не нужен
    _RELOCK_GAP_S = 0.6            # панель пропадала столько и вернулась -> новая цель

    # РЕЖИМ ЗРЕНИЯ. True (по умолчанию) — ДВА окна зрения, как и задумано:
    #   * панель цели (маленькое окно) — единственный источник правды "цель
    #     выбрана / жива / сколько HP", от неё зависят переходы SEARCH <->
    #     COMBAT и захват;
    #   * мировой HP-бар над мобом (большое окно) — ищет цели в кадре: фаза
    #     SCAN замечает бары, фаза APPROACH подводит камеру и бежит к далёкому
    #     мобу, в бою он же доводит камеру на цель.
    # Это возвращено 2026-10-02: без мирового окна бот находил мобов только
    # слепым Tab и осмотром и не умел идти к далёким целям.
    # Цена: мировой бар иногда ловит ложные цели (трава, камни) — от этого
    # защищают проверка таблички с именем, липкий захват бара и подтверждение
    # через панель; отладочные рамки видны в окне песочницы vision_manager.py.
    # И ещё: поиск баров на области 1407x411 каждый тик стоит FPS.
    # False — запасной режим "только панель": мировой бар не читается совсем,
    # мобов ищут Tab (раз в 2-3 с) и круговой осмотр. Код зрения оба режима
    # поддерживает, переключатель — только эта строка.
    _USE_WORLD_VISION = True

    # Как часто жать Tab в фазе SCAN в режиме "только панель" (при
    # _USE_WORLD_VISION = False; с мировым зрением — _SEARCH_RETRY_TAB_S).
    # Раз бары не видны, Tab — единственный способ найти моба, поэтому чаще, чем в
    # режиме с мировым зрением (_SEARCH_RETRY_TAB_S). Не чаще 2 с: Tab
    # перебирает цели по кругу, а панели нужно время появиться.
    _SCAN_TAB_PANEL_ONLY_S = (2.0, 3.0)

    # Заглушка вместо мирового бара в режиме "только панель": "бара нет".
    _NO_WORLD_BAR = TargetInfo(found=False, hp_percent=0.0, offset_x=0.0, offset_y=0.0)

