    # --- Замок цепочек и очередь ввода ---

    def _cancel_queue(self, now: float, cut_wait: bool = False) -> None:
        """
        Единая точка сброса очереди ввода (cancel_pending_actions) + учёт замка.

        cut_wait=True (смерть/потеря цели): заодно обрываем идущую паузу каста,
        цепочка считается снятой. cut_wait=False (вход в бой, смена цели): то,
        что ещё не началось, выбрасываем, текущий шаг доигрывается — но
        оставшиеся шаги цепочки уже не придут, поэтому нижнюю границу конца
        (min_end) схлопываем в "сейчас": замок снимется, как только очередь
        реально опустеет (is_idle), без ожидания шагов, которых не будет.

        Флаг передаём ТОЛЬКО когда он True: так фейковый ввод старых тестов с
        сигнатурой cancel_pending_actions(self) продолжает работать.
        """
        self._freeze_inflight_chain(now)
        if cut_wait:
            self.input_manager.cancel_pending_actions(cut_current_wait=True)
            if self._chain_inflight is not None:
                gamepad_debug_logger.debug(
                    "CHAIN   '%s' снята обрывом (цель пропала), шла %.1f с",
                    self._chain_inflight["name"], now - self._chain_inflight["start"],
                )
            self._chain_inflight = None
            self._chain_free_at = float("-inf")
        else:
            self.input_manager.cancel_pending_actions()
            if self._chain_inflight is not None:
                self._chain_inflight["min_end"] = now

    def _freeze_inflight_chain(self, now: float) -> None:
        """
        Цепочка в полёте, а очередь сейчас сбросят (смерть/смена цели): запоминаем ВСЕ её
        шаги с метками. Какие уже нажаты, выясним позже, при доигрывании (combo_done): к тому
        времени поток кнопок точно закончит шаг, который нажимался в момент сброса, и не
        будет повторного нажатия.
        """
        ch = self._chain_inflight
        if ch is None or ch.get("run_id") is None or not ch.get("steps"):
            return
        self._chain_frozen = {"name": ch["name"], "run_id": ch["run_id"], "steps": ch["steps"],
                              "frozen_at": now}

    def _resume_frozen_chain(self, now: float) -> bool:
        """
        Доиграть ненажатые скиллы замороженной цепочки на текущей цели. Зовётся из ротации,
        когда урон уже идёт и замок свободен. True — поставили скиллы в очередь.
        Перезарядку самой цепочки не трогаем: она считается от её первого запуска.
        """
        fr = getattr(self, "_chain_frozen", None)
        if fr is None:
            return False
        self._chain_frozen = None
        if now - fr["frozen_at"] > self._CHAIN_FROZEN_MAX_S:
            gamepad_debug_logger.debug("CHAIN   заморозку '%s' забываю: прошло %.0f с", fr["name"], now - fr["frozen_at"])
            return False
        done = self.input_manager.combo_done if self._input_tracks_chains() else None
        left = [st for i, st in enumerate(fr["steps"]) if not (done and done((fr["run_id"], i)))]
        if not left:
            return False
        gamepad_debug_logger.debug("CHAIN   RESUME '%s': доигрываю %d скилл(ов), не нажатых до смерти цели",
                                   fr["name"], len(left))
        self._start_chain_steps(now, fr["name"] + " (доигрываю)", left)
        return True

    def _input_tracks_chains(self) -> bool:
        """
        Умеет ли ввод помечать нажатые скиллы (метки tag + combo_done). Проверяем по КЛАССУ,
        а не hasattr(объект): у заглушек с __getattr__ hasattr отвечает True на любое имя,
        и бот передал бы tag= в execute_combo, который его не принимает (TypeError).
        """
        return callable(getattr(type(self.input_manager), "combo_done", None))

    def _start_chain_steps(self, now: float, name: str, steps: "list[tuple[list[str], float | None]]") -> None:
        """Поставить скиллы цепочки в очередь с метками и поднять замок (_chain_inflight)."""
        self._chain_run_seq = getattr(self, "_chain_run_seq", 0) + 1
        run_id = self._chain_run_seq
        tagged = self._input_tracks_chains()
        for i, (combo, cast_time_s) in enumerate(steps):
            if tagged:
                self.input_manager.execute_combo(combo, cast_time_s=cast_time_s, tag=(run_id, i))
            else:
                self.input_manager.execute_combo(combo, cast_time_s=cast_time_s)
        min_s = self._chain_min_duration({"gamepad_steps": [st[0] for st in steps],
                                          "cast_times": [st[1] for st in steps]})
        self._chain_inflight = {
            "name": name, "start": now, "min_end": now + min_s, "n_steps": len(steps),
            "run_id": run_id if tagged else None, "steps": list(steps),
        }
        gamepad_debug_logger.debug(
            "CHAIN   START '%s': %d скилл(ов), не короче %.1f с — до конца замок", name, len(steps), min_s,
        )

    def _chain_min_duration(self, chain: dict) -> float:
        """
        НИЖНЯЯ оценка длительности цепочки в секундах: на каждый скилл — минимум
        его нажатий плюс минимальная пауза после него (для долгого каста — не
        короче самого каста, иначе пауза без заданного каста). Чистая функция
        от chain — гоняется в песочнице на любом словаре из skills_config.
        """
        total = 0.0
        for steps, cast_time_s in zip(chain["gamepad_steps"], chain["cast_times"]):
            total += len(steps) * self._CHAIN_MIN_ACTION_S
            total += (
                cast_time_s * self._CHAIN_CAST_GAP_FACTOR
                if cast_time_s is not None else self._CHAIN_MIN_GAP_S
            )
        return total

    def request_chains_reload(self, chains: "list[dict]") -> None:
        """
        Приложение сохранило конфиг, бот работает -> новые цепочки вступят в силу
        на следующем тике (~16 мс), без перезапуска бота. Зовётся из потока
        интерфейса, поэтому только кладёт список "в почтовый ящик": одно
        присваивание ссылки атомарно под GIL, а саму замену делает поток FSM
        (см. run()). Как проверить без игры: FarmBot.__new__, подставь _chains,
        выставь одной next_ready_at, вызови _apply_chains(новый список) — кулдаун
        должен переехать в цепочку с тем же id, порядок — стать новым.
        """
        self._pending_chains = chains

    def _apply_chains(self, chains: "list[dict]") -> None:
        """Заменить цепочки, сохранив кулдауны тех, что были (по id) — иначе после
        каждой правки в приложении все цепочки разом стали бы "готовы"."""
        old = {c.get("id", c["name"]): c for c in self._chains}
        for c in chains:
            prev = old.get(c.get("id", c["name"]))
            if prev is not None:
                c["next_ready_at"] = prev["next_ready_at"]
        self._chains = chains
        gamepad_debug_logger.debug(
            "CONFIG  цепочки обновлены на лету, порядок: %s", [c["name"] for c in chains]
        )

    def _chain_busy(self, now: float) -> bool:
        """
        Замок: True — новую цепочку (и автоатаку) ставить НЕЛЬЗЯ.
        Цепочка считается законченной, когда выполнены оба условия сразу:
        очередь ввода пуста (is_idle) И прошла нижняя оценка min_end. Тогда
        снимаем замок, пишем CHAIN END и заводим хвостовую паузу.
        Дёшево: зовётся каждый тик, внутри — сравнение чисел и один is_idle().
        """
        ch = self._chain_inflight
        if ch is not None:
            if now < ch["min_end"] or not self.input_manager.is_idle():
                return True
            self._chain_inflight = None
            tail = random.uniform(*self._CHAIN_TAIL_S)
            self._chain_free_at = now + tail
            gamepad_debug_logger.debug(
                "CHAIN   END '%s': шла %.1f с (минимум %.1f с), хвостовая пауза %.2f с",
                ch["name"], now - ch["start"], ch["min_end"] - ch["start"], tail,
            )
        return now < self._chain_free_at

    def _press_tab(self, now: float, where: str) -> None:
        """
        Tab (смена цели) + учёт для диагностики. Всё нажатие — через
        InputManager.flick_target(); здесь только запоминаем момент, чтобы
        _note_tab_result потом написал, взял ли Tab цель и за сколько.
        Если по предыдущему Tab вердикта ещё нет (панель так и не появилась,
        а мы уже жмём следующий) — пишем его здесь, иначе он потерялся бы.
        """
        if self._tab_pressed_at is not None:
            gamepad_debug_logger.debug(
                "TABRES  Tab #%d: панели нет через %.1f с — цель не взята",
                self._tab_seq, now - self._tab_pressed_at,
            )
        self._tab_seq += 1
        self._tab_pressed_at = now
        gamepad_debug_logger.debug("TAB     #%d (%s)", self._tab_seq, where)
        self.input_manager.flick_target(self._SEARCH_FLICK_DIRECTION)

    def _note_tab_result(self, now: float, panel_found: bool, hp: float) -> None:
        """
        Зовётся каждый тик SEARCH. Вердикт по последнему Tab: панель появилась
        (с каким HP и через сколько) или не появилась за _TAB_RESULT_WAIT_S.
        По этим строкам видно, КОГДА Tab не берёт цель, а не бот тормозит:
        "панели нет" = игра не выбрала моба (вне радиуса/нейтральный).
        """
        t = self._tab_pressed_at
        if t is None:
            return
        if panel_found:
            gamepad_debug_logger.debug(
                "TABRES  Tab #%d: панель появилась через %.2f с (hp=%.0f%%)",
                self._tab_seq, now - t, hp,
            )
            self._tab_pressed_at = None
        elif now - t >= self._TAB_RESULT_WAIT_S:
            gamepad_debug_logger.debug(
                "TABRES  Tab #%d: панели нет через %.1f с — цель не взята",
                self._tab_seq, now - t,
            )
            self._tab_pressed_at = None

    def _set_phase(self, phase: SearchPhase, now: float, why: str) -> None:
        """
        Смена фазы поиска: единая точка, где фаза меняется, лог пишется и
        заводятся таймеры новой фазы. Одно место = нельзя забыть сбросить
        что-то при одном из переходов.
        """
        old = self._search_phase
        self._search_phase = phase
        logger.info("SEARCH: %s -> %s (%s).", old.name, phase.name, why)
        gamepad_debug_logger.debug("PHASE   %s -> %s (%s)", old.name, phase.name, why)
        self._bars_since = None
        self._vt_look_until = None
        if phase is SearchPhase.SCAN:
            self._scan_entered_at = now          # таймер RECOVERY — от входа в осмотр
            self._scan_next_tab_at = now + self._scan_tab_delay()
            self._scan_next_walk_at = now + random.uniform(*self._SCAN_WALK_EVERY_S)
        elif phase is SearchPhase.TAB:
            self._tab_attempts_left = random.randint(*self._SEARCH_TAB_ATTEMPTS)

    def _track_bars(self, now: float, aim_info: TargetInfo) -> None:
        """
        Учёт "бар виден непрерывно" для фаз TAB и SCAN. Пока бар не виден —
        снимаем захват зрения (release_bar_lock): липкий захват нужен
        бою и подходу, а при поиске он держал бы бар, давно уехавший из
        кадра, и не давал бы заметить НОВЫЙ.
        """
        if aim_info.found:
            if self._bars_since is None:
                self._bars_since = now
                self._bars_persist_need = random.uniform(*self._SEARCH_BARS_PERSIST_S)
            return
        self._bars_since = None
        if getattr(self.vision, "bar_locked", False):
            getattr(self.vision, "release_bar_lock", lambda: None)()

    def _bars_stable(self, now: float) -> bool:
        return self._bars_since is not None and now - self._bars_since >= self._bars_persist_need

    # --- Фаза TAB ---

    def _search_tab(self, now: float) -> None:
        """
        2-3 нажатия Tab с паузой ~1 с. Паузу даёт тот же _next_action_at:
        после последнего Tab ждём ещё один интервал — панель успевает
        появиться, и только потом решаем, что Tab не сработал.
        """
        # is_idle(): Tab только при пустой очереди ввода. Иначе Tab вставал в
        # очередь за паузой каста и падал пачкой с соседними (см. _KILL_CUTS_CAST_WAIT).
        if now < self._next_action_at or not self.input_manager.is_idle():
            return
        if self._VISION_TARGETING and self._USE_WORLD_VISION:
            # Цель выбирает зрение: моб в кадре -> к ближнему; нет -> осмотр камерой
            # (Tab — только запасной, в осмотре, когда никого не видно).
            if self._bars_stable(now):
                self._enter_approach(now, "зрение: ближний моб в кадре")
                return
            if self._vt_look_until is None:
                self._vt_look_until = now + random.uniform(*self._VT_FIRST_LOOK_S)
            if now >= self._vt_look_until:
                self._set_phase(SearchPhase.SCAN, now, "зрение: мобов в кадре нет — осмотр")
            return
        if self._tab_attempts_left > 0:
            self._press_tab(now, "фаза TAB")
            self._tab_attempts_left -= 1
            self._next_action_at = now + random.uniform(*self._SEARCH_FLICK_COOLDOWN)
            return
        # Tab не взял цель. Бар виден стабильно -> подбегаем, иначе осматриваемся.
        if self._bars_stable(now):
            self._enter_approach(now, "Tab не взял, но бар в кадре")
        else:
            self._set_phase(SearchPhase.SCAN, now, "Tab не взял, баров в кадре нет")

    # --- Фаза SCAN ---

    def _search_scan(self, now: float) -> None:
        """
        Осмотр: камера водит сама (InputManager.start_scan), мы только
        ждём бар, иногда пробуем Tab и иногда делаем шаг вперёд.
        """
        # Идемпотентно. Вызываем КАЖДЫЙ тик, а не один раз при входе в
        # фазу: после F4/Стоп halt_immediately() выключает осмотр, и
        # так бот "самовыздоравливает" при повторном запуске.
        # RECOVERY ("камеру в пол -> вверх -> разворот") — только если за 4 с ОСМОТРА
        # никого нет. 2026-10-04: таймер считал от начала ВСЕГО поиска, поэтому после
        # любого долгого поиска (неудачный клик, подход) камера сразу уходила в пол и на
        # разворот, даже когда мобы были видны. И при открытом списке целей разворот
        # бессмысленен: список видит мобов вокруг без камеры — пустой список = в 40 м
        # никого, и поворот камеры этого не изменит.
        # 2026-10-04: быстрый разворот RECOVERY ("пол -> вверх -> 3000 px") убран по
        # просьбе пользователя: слишком резкий, зрение на такой скорости ничего не
        # успевает увидеть. Остался плавный круговой осмотр (ScanTuning: ~10 с на 360).
        self.input_manager.start_scan()

        if self._bars_stable(now):
            self._enter_approach(now, "бар в кадре во время осмотра")
            return

        if now >= self._scan_next_tab_at and self.input_manager.is_idle():
            self._press_tab(now, "фаза SCAN")
            self._scan_next_tab_at = now + self._scan_tab_delay()
            return

        # is_idle(): не копим шаги в очереди, пока предыдущий не доигран.
        # Шаги вперёд в осмотре не нужны, когда бот и так всё время в движении (movement).
        if (
            self._SCAN_WALK_ENABLED
            and not self._movement_on()
            and now >= self._scan_next_walk_at
            and self.input_manager.is_idle()
        ):
            self.input_manager.move("forward", random.uniform(*self._SCAN_WALK_DURATION_S))
            self._scan_next_walk_at = now + random.uniform(*self._SCAN_WALK_EVERY_S)

    # --- Фаза APPROACH ---


    def _search_recovery(self, now: float) -> None:
        if not hasattr(self, "_recovery_step"):
            self._recovery_step = 0
            self._recovery_wait = 0.0

        if now < getattr(self, "_recovery_wait", 0.0):
            return

        if self._recovery_step == 0:
            self.input_manager.stop_scan()
            # Удар об пол (камера смотрит максимально вниз)
            self.input_manager.aim_with_stick(0, 5000)
            self._recovery_wait = now + 1.0
            self._recovery_step = 1
        elif self._recovery_step == 1:
            # Поднимаем на уровень горизонта
            self.input_manager.aim_with_stick(0, -1500)
            self._recovery_wait = now + 1.0
            self._recovery_step = 2
        elif self._recovery_step == 2:
            # Делаем оборот на 360 (по оси X)
            self.input_manager.aim_with_stick(3000, 0)
            self._recovery_wait = now + 1.5
            self._recovery_step = 3
        elif self._recovery_step == 3:
            # Возвращаемся в обычный скан
            self._search_entered_at = now
            self._set_phase(SearchPhase.SCAN, now, "калибровка завершена")
            delattr(self, "_recovery_step")
            
    # --- Список целей "Астрального зрения" ---

    def _list_camera(self, now: float, aim_info: TargetInfo) -> None:
        """
        Камера в бою с целью из списка (просьба пользователя 2026-10-04):
          - полоска НАШЕЙ цели в кадре (в бою aim_info ищется только с меткой выбора) ->
            осмотр стоп, мягко доводим в прицел (gentle: вдвое медленнее обычного);
          - не видно дольше _LIST_CAM_LOST_S -> плавный круговой осмотр (~10 с на 360°),
            пока не найдём; за _LIST_CAM_SEARCH_MAX_S не нашли -> камеру не трогаем.
        Как проверить без игры: сценарий с фейковым зрением — метка появляется через N с,
        в логе ввода сначала start_scan, потом stop_scan и мягкий aim (gentle=True).
        """
        # Сначала по НОМЕРУ над мобом (тот же, что у строки в списке): точно наш моб,
        # работает и у агрессивных, где стрелки выбора распознаются плохо. Нет номера
        # (цифра без образца, номер за краем зоны) — по стрелкам выбора (aim_info).
        number = self._list_target_number()
        target, how = self._list_track(now, number)
        if not target.found:
            target, how = aim_info, "стрелки"
            if aim_info.found:
                self._lt_lock_marked(now)          # по стрелкам нашли — дальше ведём по месту
                if number is not None:
                    self._save_world_number_sample(number)
        if target.found:
            if getattr(self, "_list_cam_scanning", False) or getattr(self, "_list_cam_how", None) != how:
                if getattr(self, "_list_cam_scanning", False):
                    self.input_manager.stop_sweep()
                self._list_cam_scanning = False
                self._list_cam_how = how
                gamepad_debug_logger.debug("CAMERA  цель в кадре (%s) — веду плавно", how)
            self._list_cam_seen_at = now
            mv = getattr(self, "movement", None)
            if (getattr(self, "_cam_turn_req", False) or getattr(self, "_cam_look_total", 0.0) > 0) \
                    and mv is not None and hasattr(mv, "cancel_turn"):
                mv.cancel_turn()                   # цель нашлась — поворот "куда бегу"/осмотр больше не нужен
                self._cam_turn_req = False
            self._camera_reset_look()
            self._camera_comfort(now, target.offset_x)
            return
        if now - getattr(self, "_list_cam_seen_at", float("-inf")) < self._LIST_CAM_LOST_S:
            return
        self._cam_correcting = False
        if self.state is State.COMBAT and (getattr(self, "_engaged", False) or getattr(self, "_lp_in_melee", False)):
            # Ближний бой, полоски цели в кадре нет (моб вплотную, полоска над краем): крутить
            # камеру по кругу — не по-человечески и сбивает обзор. Стоим, ждём, пока покажется.
            if getattr(self, "_list_cam_scanning", False):
                self.input_manager.stop_sweep()
                self._list_cam_scanning = False
                gamepad_debug_logger.debug("CAMERA  ближний бой, цели в кадре нет — разворот остановлен")
            return
        if self.state is State.COMBAT and self._camera_face_run(now):
            return
        started = getattr(self, "_list_cam_search_started", now)
        if now - started > self._LIST_CAM_SEARCH_MAX_S:
            if getattr(self, "_list_cam_scanning", False):
                self.input_manager.stop_sweep()
                self._list_cam_scanning = False
                gamepad_debug_logger.debug("CAMERA  цель за %.0f с осмотра не нашлась — камеру оставляю",
                                           self._LIST_CAM_SEARCH_MAX_S)
            return
        if self._gestures_ok():
            if getattr(self, "_list_cam_scanning", False):
                self.input_manager.stop_sweep()
                self._list_cam_scanning = False
            self._camera_look_around(now)
            return
        if not getattr(self, "_list_cam_scanning", False):
            self.input_manager.clear_aim_target()
            self._list_cam_scanning = True
            gamepad_debug_logger.debug("CAMERA  цели в кадре нет — плавный разворот по горизонтали")
        self.input_manager.start_sweep()         # идемпотентно: сторона и скорость не меняются

    def _gestures_ok(self) -> bool:
        """Камера жестами из записи: есть контроллер движения с жестами и ввод умеет camera_nudge."""
        mv = getattr(self, "movement", None)
        return (mv is not None and bool(getattr(mv, "_turns", None))
                and hasattr(type(self.input_manager), "camera_nudge"))

    def _counts_per_deg(self) -> float:
        nav = getattr(self, "navigator", None)
        return nav.counts_per_deg if nav is not None else 6000.0 / 360.0

    def _camera_gesture_aim(self, now: float, dx: float) -> None:
        """
        Цель в кадре, "упор на цель" жестами: вышла за _CAM_ZONE_OUT -> после реакции один
        жест на нужный угол (dx / gain, чуть недоводя), потом пауза-проверка, и снова, если
        надо. После каждого жеста уточняем gain: на сколько px сдвинулась цель / счётчики.
        """
        mv = self.movement
        pend = getattr(self, "_cam_pending", None)
        if pend is not None:
            if mv.turn_active:
                return                               # жест ещё играется
            if getattr(self, "_cam_verify_at", None) is None:
                self._cam_verify_at = now + random.uniform(*self._CAM_VERIFY_S)
                return
            if now < self._cam_verify_at:
                return                               # "посмотреть, где цель" — как человек после рывка мышью
            dx0, counts = pend
            self._cam_pending = None
            self._cam_verify_at = None
            moved = dx0 - dx
            if abs(counts) >= 60 and moved * counts > 0:
                lo, hi = self._CAM_GAIN_RANGE
                g_obs = min(hi, max(lo, moved / counts))
                # Первые два замера — с большим весом (стартовое 2.0 лишь догадка), дальше спокойнее:
                # замер на бегу шумный, один кривой не должен раскачать камеру.
                n = getattr(self, "_cam_gain_n", 0)
                alpha = 0.7 if n < 2 else 0.4
                self._cam_gain_n = n + 1
                self._cam_gain = (1 - alpha) * getattr(self, "_cam_gain", self._CAM_GAIN0) + alpha * g_obs
        w = float(getattr(self.vision, "screen_w", 1920) or 1920)
        if abs(dx) <= self._CAM_ZONE_OUT * w:
            self._cam_out_since = None
            return
        since = getattr(self, "_cam_out_since", None)
        if since is None:
            self._cam_out_since = since = now
            self._cam_react = random.uniform(*self._CAM_REACT_S)
        if now - since < getattr(self, "_cam_react", 0.0):
            return
        self._cam_out_since = None
        gain = getattr(self, "_cam_gain", self._CAM_GAIN0)
        counts = dx / gain * random.uniform(*self._CAM_AIM_FRAC)
        self.input_manager.clear_aim_target()     # камера — только жестом: поток плавного ведения не мешает
        if mv.request_turn(counts):
            self._cam_pending = (dx, counts)
            self._cam_verify_at = None
            gamepad_debug_logger.debug("CAMERA  упор на цель: жест %+.0f счётчиков (цель в %+.0f px, %.2f px/сч)",
                                       counts, dx, gain)

    def _camera_look_around(self, now: float) -> None:
        """Цели в кадре нет: осмотр жестами по 60-100° с паузами, не больше полного круга."""
        mv = self.movement
        if mv.turn_active:
            self._cam_look_wait_from = None
            return
        if getattr(self, "_cam_look_total", 0.0) >= 360.0:
            if not getattr(self, "_cam_look_done_logged", False):
                self._cam_look_done_logged = True
                gamepad_debug_logger.debug("CAMERA  осмотрелся по кругу — цель не видна, камеру оставляю")
            return
        wait_from = getattr(self, "_cam_look_wait_from", None)
        if wait_from is None:
            self._cam_look_wait_from = wait_from = now
            self._cam_look_pause = random.uniform(*self._CAM_LOOK_PAUSE_S)
        if now - wait_from < self._cam_look_pause:
            return
        if getattr(self, "_cam_look_dir", 0) == 0:
            self._cam_look_dir = random.choice((-1, 1))
        deg = random.uniform(*self._CAM_LOOK_STEP_DEG)
        if mv.request_turn(self._cam_look_dir * deg * self._counts_per_deg()):
            self._cam_look_total = getattr(self, "_cam_look_total", 0.0) + deg
            self._cam_look_wait_from = None
            gamepad_debug_logger.debug("CAMERA  цели в кадре нет — осматриваюсь жестом на %+.0f°", self._cam_look_dir * deg)

    def _camera_reset_look(self) -> None:
        self._cam_look_total = 0.0
        self._cam_look_dir = 0
        self._cam_look_wait_from = None
        self._cam_look_done_logged = False

    def _camera_comfort(self, now: float, dx: float) -> None:
        """
        Цель в кадре: держим её в удобной зоне у центра, как человек. Только по горизонтали
        (dy=0): наклон не трогаем — ведение по вертикали укладывало камеру в пол (скрин 09:49).
        Гистерезис (выйти за 10% ширины / вернуться в 3%) — чтобы не дёргать камеру на
        каждом пикселе; задержка реакции — человек замечает, что цель уехала, не мгновенно.
        """
        if self._gestures_ok():
            self._camera_gesture_aim(now, dx)
            return
        w = float(getattr(self.vision, "screen_w", 1920) or 1920)
        if getattr(self, "_cam_correcting", False):
            if abs(dx) <= self._CAM_ZONE_IN * w:
                self._cam_correcting = False
                self.input_manager.clear_aim_target()
                return
        else:
            if abs(dx) <= self._CAM_ZONE_OUT * w:
                self._cam_out_since = None
                return
            since = getattr(self, "_cam_out_since", None)
            if since is None:
                self._cam_out_since = since = now
                self._cam_react = random.uniform(*self._CAM_REACT_S)
            if now - since < getattr(self, "_cam_react", 0.0):
                return
            self._cam_correcting = True
            self._cam_out_since = None
        # adaptive — поправка на то, что близкий моб едет по экрану медленнее.
        self.input_manager.aim_with_stick(dx, 0.0, adaptive=True, gentle=True)

    def _camera_face_run(self, now: float) -> bool:
        """
        Цели в кадре нет, персонаж бежит к ней сам (клик по списку): поворачиваем камеру
        туда, куда он бежит — цель окажется впереди, и её подхватит слежение. Направление
        бега — сдвиг миникарты; курс камеры — последний замер + повороты с тех пор.
        True — камерой занялись (или уже смотрим куда надо), разворот по кругу не нужен.
        """
        nav, mv = getattr(self, "navigator", None), getattr(self, "movement", None)
        if nav is None or mv is None or not hasattr(mv, "request_turn"):
            return False
        if getattr(self, "_cam_turn_req", False) and mv.turn_active:
            return True
        yaw_fn = getattr(self.input_manager, "camera_yaw_counts", None)
        cam = nav.camera_heading(yaw_fn() if yaw_fn is not None else None, now)
        run = nav.motion_bearing(now)
        if cam is not None and run is None and now - getattr(self, "_list_cam_search_started", now) < 1.5:
            return True                            # курс камеры знаем, направление бега будет через ~1 с — подождём
        if cam is None or run is None:
            return False
        err = wrap180(run - cam)
        if abs(err) < self._CAM_FACE_TOL_DEG:
            if getattr(self, "_list_cam_scanning", False):
                self.input_manager.stop_sweep()
                self._list_cam_scanning = False
            return True                            # смотрим, куда бежим; цель впереди, просто ещё не видна
        if now < getattr(self, "_cam_turn_next_at", 0.0):
            return True
        self.input_manager.stop_sweep()
        self.input_manager.clear_aim_target()
        self._list_cam_scanning = False
        if not mv.request_turn(nav.turn_counts(err)):
            return False
        self._cam_turn_req = True
        self._cam_turn_next_at = now + 1.2
        gamepad_debug_logger.debug("CAMERA  цели в кадре нет — смотрю, куда бегу: поворот %+.0f°", err)
        return True

    def _list_track(self, now: float, number: "int | None") -> "tuple[TargetInfo, str]":
        """
        Наша цель на экране: ведём захваченную полоску по месту (ближайшая к прошлой точке
        в радиусе _LT_TRACK_RADIUS_PX), раз в _LT_VERIFY_EVERY_S сверяем номер над ней.
        Захвата нет или он потерян дольше _LIST_CAM_LOST_S — ищем заново по ТЕКУЩЕМУ
        номеру выбранной строки списка (после перенумерации он уже новый).
        """
        none = TargetInfo(found=False, hp_percent=0.0, offset_x=0.0, offset_y=0.0)
        bars_fn = getattr(self.vision, "world_bars", None)
        if bars_fn is None:                        # зрение без слежения (моки) — как раньше, по номеру
            find = getattr(self.vision, "find_numbered_bar", None)
            if number is not None and find is not None:
                ti = find(number)
                if ti.found:
                    return ti, "номер %d" % number
            return none, ""
        bars = bars_fn()
        anchor = self.vision.bar_anchor
        lock = getattr(self, "_lt_lock", None)
        if lock is not None:
            near = [b for b in bars if math.hypot(anchor(b)[0] - lock[0], anchor(b)[1] - lock[1]) <= self._LT_TRACK_RADIUS_PX]
            if near:
                best = min(near, key=lambda b: math.hypot(anchor(b)[0] - lock[0], anchor(b)[1] - lock[1]))
                self._lt_lock = anchor(best)
                self._lt_seen_at = now
                if now - getattr(self, "_lt_verified_at", 0.0) >= self._LT_VERIFY_EVERY_S:
                    self._lt_verified_at = now
                    n = self.vision.bar_number(best)
                    if n is not None and number is not None and n != number:
                        self._lt_mismatch = getattr(self, "_lt_mismatch", 0) + 1
                    elif n is not None:
                        self._lt_mismatch = 0
                    if getattr(self, "_lt_mismatch", 0) >= self._LT_MISMATCH_DROP:
                        gamepad_debug_logger.debug("CAMERA  под захватом номер %s, а у цели %s — ищу заново", n, number)
                        self._lt_lock = None
                if getattr(self, "_lt_lock", None) is not None:
                    return self.vision.bar_info(best), "слежение"
            elif now - getattr(self, "_lt_seen_at", now) > self._LIST_CAM_LOST_S:
                self._lt_lock = None
            else:
                return none, ""                    # на миг закрыло (дерево, эффект) — ждём на месте
        if number is not None:
            for b in bars:
                if self.vision.bar_number(b) == number:
                    self._lt_lock = anchor(b)
                    self._lt_seen_at = self._lt_verified_at = now
                    self._lt_mismatch = 0
                    return self.vision.bar_info(b), "номер %d" % number
        return none, ""

    def _lt_lock_marked(self, now: float) -> None:
        """Цель нашлась по стрелкам выбора — захватываем её полоску и дальше ведём по месту."""
        marked = getattr(self.vision, "last_marked_bars", None)
        anchor = getattr(self.vision, "bar_anchor", None)
        if marked and anchor is not None:
            self._lt_lock = anchor(marked[0])
            self._lt_seen_at = self._lt_verified_at = now
            self._lt_mismatch = 0

    def _lt_reset(self) -> None:
        self._lt_lock = None
        self._lt_mismatch = 0

    def _list_progress(self, now: float) -> None:
        """
        Бой с целью из списка, урона ещё нет: следим за расстоянием выбранной строки.
        Падает — бежим, цель не бросаем. Не уменьшилось на _LP_MIN_GAIN_M за _LP_STUCK_S —
        моб недосягаем (за скалой, на обрыве): смена цели через список.
        """
        if self._engaged:
            return
        tl = getattr(self, "_list_last", None)
        sel = tl.selected_row if tl is not None and tl.visible else None
        if self._lp_check_faded(now, sel):
            return
        d = sel.distance_m if sel is not None else None
        if d is None:
            return
        nav = getattr(self, "navigator", None)
        if nav is not None:
            nav.observe_target_distance(d)        # бежим к мобу сами: метры списка vs сдвиг карты = масштаб
        if d <= self._LP_MELEE_M:
            # Добежали: на первый удар даём 5 с, дальше обычный сторож (_engage_timeout).
            self._eg_deadline = min(self._eg_deadline, now + 5.0) if not getattr(self, "_lp_in_melee", False) else self._eg_deadline
            self._lp_in_melee = True
            return
        best = getattr(self, "_lp_best", None)
        if best is None or d <= best - self._LP_MIN_GAIN_M:
            self._lp_best, self._lp_best_at = d, now
            return
        if now - self._lp_best_at >= self._LP_STUCK_S and self.input_manager.is_idle():
            gamepad_debug_logger.debug(
                "PROGRESS расстояние до цели не уменьшается %.1f с (%d м) и урона нет — моб недосягаем",
                now - self._lp_best_at, d)
            if not self._try_list_switch(now):
                self._lp_best_at = now           # менять не на кого — подождём ещё

    def _lp_check_faded(self, now: float, sel) -> bool:
        """
        Выбранная строка серая _LP_FADED_CONFIRM_S подряд, а урона ещё нет -> моб ушёл, бежать
        к нему бессмысленно: смена через список. True — ушли менять цель. Бьём уже — не
        трогаем (сюда не попадём: _list_progress зовётся только до первого урона).
        """
        if sel is None or not getattr(sel, "faded", False):
            self._lp_faded_since = None
            return False
        since = getattr(self, "_lp_faded_since", None)
        if since is None:
            self._lp_faded_since = now
            return False
        if now - since < self._LP_FADED_CONFIRM_S or not self.input_manager.is_idle():
            return False
        self._lp_faded_since = None
        gamepad_debug_logger.debug("FADED   выбранная цель №%d посерела в списке (ушла далеко) до первого удара",
                                   sel.index)
        return self._try_list_switch(now, why="цель посерела")

    def _list_target_number(self) -> "int | None":
        """Номер нашей цели: выбранная строка списка, а до того — строка, по которой кликнули."""
        tl = getattr(self, "_list_last", None)
        if tl is not None and tl.visible and tl.selected_row is not None:
            return tl.selected_row.index
        row = getattr(self, "_list_row", None)
        return row.index if row is not None else None

    def _save_world_number_sample(self, number: int) -> None:
        """
        Номер без образца (4, 6, 7, 8): цель нашлась по стрелкам, а номер её строки мы
        знаем из списка — сохраняем окно номера с правильной подписью (до 6 на цифру).
        По ним добавим образцы, и такие номера тоже начнут находиться.
        """
        fn = getattr(self.vision, "number_window_of_marked", None)
        writer = getattr(getattr(self, "_hp_collector", None), "writer", None)
        if fn is None or writer is None:
            return
        counts = self.__dict__.setdefault("_world_num_saved", {})
        if counts.get(number, 0) >= 6:
            return
        win = fn()
        if win is None:
            return
        counts[number] = counts.get(number, 0) + 1
        path = os.path.join(_PROJECT_ROOT, "world_number_samples", "%d_%02d.png" % (number, counts[number]))
        writer.submit(_imwrite, path, win.clip(0, 255).astype("uint8"))

    def _list_drives(self) -> bool:
        """Список целей открыт -> цель выбирает он, камера боту не нужна (ни в поиске, ни в бою)."""
        if not self._LIST_TARGETING:
            return False
        tl = getattr(self, "_list_last", None)
        return tl is not None and tl.visible

    def _refresh_list(self, now: float):
        """
        Свежий разбор списка не чаще _LIST_READ_EVERY_S (иначе — прошлый). None —
        список выключен или у зрения нет метода (моки старых тестов). Смена списка
        пишется в лог строкой LIST, неуверенные цифры — в list_digit_samples/.
        """
        if not self._LIST_TARGETING:
            return None
        fn = getattr(self.vision, "get_target_list", None)
        if fn is None:
            return None
        if now >= getattr(self, "_list_next_read_at", 0.0):
            self._list_next_read_at = now + self._LIST_READ_EVERY_S
            tl = fn()
            self._list_last = tl
            if tl.visible:
                self._list_ever_seen = True
                if getattr(self, "_list_gone_logged", False):
                    self._list_gone_logged = False
                    gamepad_debug_logger.debug("LIST    список целей снова виден")
            text = format_list(tl)
            if text != getattr(self, "_list_last_text", None):
                self._list_last_text = text
                gamepad_debug_logger.debug("LIST    %s", text)
            self._save_list_glyphs(tl)
        return getattr(self, "_list_last", None)

    def _save_list_glyphs(self, tl) -> None:
        """Цифры, узнанные неуверенно (0 и 5 пока без образцов) — на диск, в фоне."""
        if not tl.unsure_glyphs:
            return
        seen = self.__dict__.setdefault("_list_glyph_seen", set())
        writer = getattr(getattr(self, "_hp_collector", None), "writer", None)
        if writer is None:
            return
        for guess, win in tl.unsure_glyphs:
            key = hash(win.astype("uint8").tobytes())
            if key in seen or len(seen) >= self._LIST_SAMPLES_MAX:
                continue
            seen.add(key)
            path = os.path.join(_PROJECT_ROOT, "list_digit_samples", "%s_%08x.png" % (guess, key & 0xFFFFFFFF))
            writer.submit(_imwrite, path, win.astype("uint8"))

    def _list_has_target(self, now: float) -> bool:
        """В последнем прочитанном списке есть кого кликнуть (без чтения экрана)."""
        tl = getattr(self, "_list_last", None)
        return tl is not None and tl.visible and tl.nearest(self._list_exclude(now)) is not None

    def _list_exclude(self, now: float) -> "set[int]":
        bl = self.__dict__.setdefault("_list_blacklist", {})
        return {i for i, until in bl.items() if until > now}

    def _try_list_target(self, now: float, why: str, exclude_extra: "set[int] | None" = None) -> bool:
        """
        Ближний моб из списка -> фаза LIST (клик после короткой "реакции"). True — пошли
        кликать; False — списка нет/пусто/все в чёрном списке, вызывающий ищет как раньше.
        """
        if now < self._next_action_at or not self.input_manager.is_idle():
            return False
        tl = self._refresh_list(now)
        if tl is None or not tl.visible or not tl.rows:
            return False
        exclude = self._list_exclude(now) | (exclude_extra or set())
        row = tl.nearest(exclude)
        if row is None:
            return False
        jx, jy = self._LIST_JITTER_PX
        px, py = row.click_point
        self._list_target_xy = self.vision.list_point_to_screen(
            (px + random.uniform(-jx, jx), py + random.uniform(-jy, jy)))
        self._list_row = row
        self._lt_reset()
        mv = getattr(self, "movement", None)
        if mv is not None and hasattr(mv, "cancel_turn"):
            mv.cancel_turn()                      # новая цель: жест прогулки/прошлой цели не доигрываем
        self._cam_pending = None
        self._camera_reset_look()
        self._list_clicked = False
        self._list_click_due = now + random.uniform(*self._LIST_REACTION_S)
        self.input_manager.stop_scan()
        self.input_manager.stop_sweep()
        self.input_manager.clear_aim_target()
        self._set_phase(SearchPhase.LIST, now, "%s: ближний в списке №%d (%s)" % (
            why, row.index, "?" if row.distance_m is None else "%d м" % row.distance_m))
        gamepad_debug_logger.debug("LIST    -> №%d из [%s], клик Alt+ПКМ", row.index, format_list(tl))
        return True

    def _search_list_wait(self, now: float, panel_info: TargetInfo, aim_info: TargetInfo) -> None:
        """
        Фаза LIST: кликнуть (после реакции) и ждать, пока рамка выбора в списке встанет
        на эту строку и появится панель -> COMBAT. Не вышло за _LIST_CONFIRM_TIMEOUT_S ->
        строку в чёрный список на _LIST_BLACKLIST_S, назад в TAB (там снова список/зрение).
        """
        if not self._list_clicked:
            if now >= self._list_click_due and self.input_manager.is_idle():
                # ПКМ, а не ЛКМ: по ПКМ на строке персонаж сразу бежит к мобу (проверил пользователь).
                pressed = self._clicks_pressed()
                self._list_click_press_target = None if pressed is None else pressed + 1
                self._list_click(*self._list_target_xy)
                self._list_clicked = True
                self._list_cam_scanning = False
                self._list_cam_how = None
                self._list_cam_seen_at = float("-inf")
                self._list_cam_search_started = now
                self._list_deadline = now + self._LIST_CONFIRM_TIMEOUT_S
                # Была ли панель до клика: при смене цели из боя она показывает прежнюю.
                self._list_panel_before = panel_info.found
            return
        tl = self._refresh_list(now)
        sel = tl.selected_row if tl is not None else None
        on_row = sel is not None and sel.index == self._list_row.index
        # Пока ждём подтверждения, камера уже ищет моба по номеру (по стрелкам здесь нельзя:
        # в поиске зрение не проверяет метку выбора, и aim_info может быть чужим).
        if self.input_manager.is_idle():
            self._list_camera(now, TargetInfo(found=False, hp_percent=0.0, offset_x=0.0, offset_y=0.0))
        # Подтверждение: рамка встала на эту строку; либо (если рамка обновляется не
        # сразу) панель появилась там, где до клика цели не было вовсе.
        if panel_info.found and (on_row or (not self._list_panel_before and self.input_manager.is_idle())):
            gamepad_debug_logger.debug("LIST    выбран №%d (%s) -> бой", self._list_row.index,
                                       "рамка на строке" if on_row else "появилась панель")
            self._enter_combat(now, panel_info, aim_info, via_list=True)
            return
        if now >= self._list_deadline and self.input_manager.is_idle():
            if getattr(self.input_manager, "last_click_ok", True) is False:
                # Клика не было (курсор не появился по Alt) — строка не виновата, в чёрный
                # список не заносим; попробуем ещё раз чуть позже.
                self._next_action_at = now + random.uniform(0.4, 0.8)
                self._set_phase(SearchPhase.TAB, now, "клик по №%d отменён: не появился курсор (Alt)" %
                                self._list_row.index)
                return
            self.__dict__.setdefault("_list_blacklist", {})[self._list_row.index] = now + self._LIST_BLACKLIST_S
            self._set_phase(SearchPhase.TAB, now, "клик по №%d не выбрал цель — в чёрный список на %.0f с" % (
                self._list_row.index, self._LIST_BLACKLIST_S))

    def _try_list_switch(self, now: float, why: str = "HP не менялось") -> bool:
        """
        "HP не менялось" в бою: текущую (выбранную в списке) строку — в чёрный список,
        кликаем ближнего ДРУГОГО. True — ушли в SEARCH/LIST; False — в списке некого.
        """
        tl = self._refresh_list(now)
        if tl is None or not tl.visible:
            return False
        sel = tl.selected_row
        extra = {sel.index} if sel is not None else set()
        if tl.nearest(self._list_exclude(now) | extra) is None:
            return False
        if sel is not None:
            self.__dict__.setdefault("_list_blacklist", {})[sel.index] = now + self._LIST_BLACKLIST_S
        gamepad_debug_logger.debug(
            "SWITCH  %s (без урона %.1f с) — беру ближнего другого из списка (№%s в чёрный список)",
            why, now - self._eg_wait_since, sel.index if sel is not None else "-")
        self._bb_event(now, "list_switch", {"waited_s": now - self._eg_wait_since, "why": why,
                                            "list": format_list(tl)})
        self.state = State.SEARCH
        self._cancel_queue(now)
        self._target_lost_since = None
        self._reset_search_state(now)
        self._next_action_at = now
        return self._try_list_target(now, "смена цели", exclude_extra=extra)

    def _enter_approach(self, now: float, why: str) -> None:
        self.input_manager.stop_scan()
        self._set_phase(SearchPhase.APPROACH, now, why)
        self._approach_deadline = now + random.uniform(*self._APPROACH_RUN_TIMEOUT_S)
        self._approach_clicks = 0
        self._approach_settled_since = None
        self._approach_settle_need = random.uniform(*self._APPROACH_SETTLE_S)
        self._approach_next_click_at = now
        self._approach_bar_lost_since = None

    def _abort_approach(self, now: float, why: str) -> None:
        """Подход не удался: гасим камеру и очередь, снимаем захват, назад в осмотр."""
        self.input_manager.clear_aim_target()
        self._cancel_queue(now)
        getattr(self.vision, "release_bar_lock", lambda: None)()
        self._set_phase(SearchPhase.SCAN, now, why)

    def _search_approach(self, now: float, aim_info: TargetInfo) -> None:
        """
        Подход к далёкому мобу: навести камеру на тело моба и кликнуть ПКМ.
        Цель наведения — тело моба (бар + поправка вниз, она уже внутри
        aim_info.offset_*) в ТОЧКУ ПРИЦЕЛА игры. Клик не раньше, чем камера
        продержалась в допуске _APPROACH_SETTLE_S: прицел должен
        дойти, а не "пролетать мимо" в момент клика.
        """
        if now >= self._approach_deadline:
            self._abort_approach(now, "таймаут подхода")
            return

        if not aim_info.found:
            if self._approach_bar_lost_since is None:
                self._approach_bar_lost_since = now
            elif now - self._approach_bar_lost_since > self._APPROACH_BAR_LOST_S:
                self._abort_approach(now, "бар моба потерян")
            return
        self._approach_bar_lost_since = None

        dx = aim_info.offset_x
        dy = aim_info.offset_y
        # adaptive=True: поворот к НОВОМУ мобу. Камера TL крутится вокруг персонажа,
        # и близкий моб едет по экрану в 3-5 раз медленнее дальнего — без этого
        # подход к ближнему занимал 4-6 с (лог 16:38:24 и 16:38:44). Подробно —
        # AimTuning.adapt_* в input_manager.py.
        self.input_manager.aim_with_stick(dx, dy, adaptive=True)

        if math.hypot(dx, dy) > self._APPROACH_AIM_TOL_PX:
            self._approach_settled_since = None
            return
        if self._approach_settled_since is None:
            self._approach_settled_since = now
            return
        if now - self._approach_settled_since < self._approach_settle_need:
            return
        if now < self._approach_next_click_at or self._approach_clicks >= self._APPROACH_MAX_CLICKS:
            return
        # Клик/повтор "шаг -> Tab -> ПКМ" только при пустой очереди: иначе они
        # пристраивались бы за незавершённой командой и срабатывали пачкой.
        if not self.input_manager.is_idle():
            return

        if self._approach_clicks > 0:
            # Предыдущий клик цель не выбрал. Очередь команд строго
            # последовательная (FIFO): шаг вперёд -> (Tab) -> ПКМ выполнятся
            # именно в таком порядке, ничего не перемешается. При выборе цели
            # зрением Tab здесь не жмём: он выбрал бы кого угодно, а мы идём к
            # конкретному мобу под прицелом.
            self.input_manager.move("forward", random.uniform(*self._APPROACH_RETRY_WALK_S))
            if not self._VISION_TARGETING:
                self._press_tab(now, "повтор подхода")
        self.input_manager.press_button("attack")
        # Клик по мобу под прицелом выбрал его — дальше панель показывает уже его.
        self._vision_switch_pending = False
        self._approach_clicks += 1
        self._approach_settled_since = None
        self._approach_settle_need = random.uniform(*self._APPROACH_SETTLE_S)
        self._approach_next_click_at = now + random.uniform(*self._APPROACH_RECLICK_S)
        gamepad_debug_logger.debug(
            "APPROACH клик ПКМ #%d (прицел dx=%+.0f dy=%+.0f)", self._approach_clicks, dx, dy
        )

    # --- Фаза REACQUIRE: вернуть потерянную (недобитую) цель ---

    def _begin_reacquire(self, now: float, last_hp: float, projected_hp: float) -> None:
        """
        Цель из боя пропала, но по прогнозу HP она НЕ убита (_kill_verdict).
        Переходим в SEARCH/REACQUIRE: Tab-ом перебираем цели и принимаем
        только ту, чьё HP попадает в окно "это она". Окно:
            [прогноз - допуск, последнее увиденное + допуск].
        Нижняя граница — прогноз, а не последнее увиденное: пока цель была
        вне панели, персонаж мог её ещё и побить. Верхняя — только последнее
        + допуск: HP у живого моба в бою вверх не идёт.
        Первый Tab — через _POST_KILL_DELAY, как и обычный поиск (мгновенная
        реакция за кадр — неестественный ритм).
        """
        self._set_phase(SearchPhase.REACQUIRE, now, "цель потеряна, HP было %.0f%%" % last_hp)
        tol = self._REACQUIRE_HP_TOL_PCT
        self._reacq_hp_lo = max(0.0, projected_hp - tol)
        self._reacq_hp_hi = min(100.0, last_hp + tol)
        self._reacq_deadline = now + random.uniform(*self._REACQUIRE_TIMEOUT_S)
        self._reacq_tabs = 0
        self._next_action_at = now + random.uniform(*self._POST_KILL_DELAY)
        gamepad_debug_logger.debug(
            "REACQ   ищем потерянную цель: принимаю панель с HP %.0f%%..%.0f%%, до %.1f с",
            self._reacq_hp_lo, self._reacq_hp_hi, self._reacq_deadline - now,
        )

    def _reacquire_hp_matches(self, hp: float) -> bool:
        """HP панели попадает в окно "это потерянная цель"."""
        return self._reacq_hp_lo <= hp <= self._reacq_hp_hi

    def _search_reacquire(self, now: float, panel_info: TargetInfo) -> None:
        """
        REACQUIRE: ждём паузу и жмём Tab, пока не появится панель с нужным HP
        (приём — в _handle_search) или не выйдет таймаут. Панель с чужим HP
        сюда тоже приходит: Tab нужен и тогда — это следующий моб по кругу.
        Таймаут -> обычная фаза TAB: цель могла правда умереть (прогноз ошибся
        в большую сторону), и топтаться на ней дальше смысла нет.

        Как тестировать без игры: fsm_test.py, сценарии V (фейковая панель с
        заданным HP и счётчик Tab-ов в фейковом вводе).
        """
        if now >= self._reacq_deadline:
            gamepad_debug_logger.debug(
                "REACQ   не нашли за таймаут (Tab-ов: %d) -> обычный поиск", self._reacq_tabs
            )
            self._set_phase(SearchPhase.TAB, now, "потерянную цель не нашли")
            return
        if now < self._next_action_at or not self.input_manager.is_idle():
            return
        self._press_tab(now, "REACQUIRE")
        self._reacq_tabs += 1
        self._next_action_at = now + random.uniform(*self._SEARCH_FLICK_COOLDOWN)
        gamepad_debug_logger.debug(
            "REACQ   Tab #%d (панель: %s)", self._reacq_tabs,
            "hp=%.0f%% — не та" % panel_info.hp_percent if panel_info.found else "нет",
        )

    # --- Вход в COMBAT ---

    def _mark_target(self) -> None:
        """
        Учёт "по этой цели первый удар отдан" — жмём Ctrl+ЛКМ для лока таргета. Время
        нужно детектору смены цели (_on_target_swap не реагирует чаще, чем раз в
        _SWAP_LOCK_MIN_GAP_S), флаг — ротации (скиллы только после первого удара).
        """
        # Цель выбирает СПИСОК (2026-10-04): Ctrl+ЛКМ не жмём — он выбирает того, кто под
        # прицелом, а клик в пустоту снимает цель (одна из причин "бросает недобитого").
        if not self._list_drives():
            self.input_manager.execute_combo(["hold_ctrl", "press_lock_on", "release_ctrl"])
        self._last_lock_at = time.monotonic()
        self._target_locked = True
        self._gate_logged = False

    def _enter_combat(self, now: float, panel_info: TargetInfo, aim_info: TargetInfo,
                      via_list: bool = False) -> None:
        """
        Единственный вход SEARCH -> COMBAT: панель увидела цель (любой фазой).

        Два случая по тому, КАК цель появилась:
          - из APPROACH после клика (далёкий моб): персонаж уже бежит/бьёт по
            нему, и камера уже ведёт его бар. Второй ПКМ лишний (двойной клик
            выглядит неестественно и может сбить бег), захват бара оставляем,
            жмём Ctrl+ЛКМ и включаем режим "Tab по дороге" (_tick_enroute).
          - иначе (Tab взял цель в TAB/SCAN или клика ещё не было): захват,
            пойманный при поиске, к выбранной цели отношения не имеет —
            снимаем его и берём бар заново ("ближайший к прицелу"), затем
            Ctrl+ЛКМ и "первый удар" ПКМ, чтобы персонаж пошёл бить.
        Порядок команд — "выбрали -> закрепили -> ударили"; очередь ввода
        строго последовательная, так что порядок гарантирован.
        """
        self.input_manager.stop_scan()
        # Выбрасываем то, что ещё стоит в очереди ввода с этапа поиска (например,
        # повтор подхода "шаг -> Tab -> ПКМ"): Tab, выполненный уже в бою,
        # сменил бы только что выбранную цель. Исполняемое сейчас не трогаем.
        self._cancel_queue(now)
        self._tab_pressed_at = None     # Tab-у вердикт уже не нужен: панель найдена
        clicked = via_list or (self._search_phase is SearchPhase.APPROACH and self._approach_clicks > 0)
        logger.info("SEARCH -> COMBAT: цель обнаружена (панель), фаза %s.", self._search_phase.name)
        # В gamepad_debug.log (а не только в консоль): переходы состояний
        # нужны в ОДНОМ файле вместе с VISION/COMBO/ROTATION, иначе по
        # логу невозможно понять, какое состояние породило тот или иной ввод.
        gamepad_debug_logger.debug(
            "STATE   SEARCH -> COMBAT (панель нашла цель, фаза %s, кликов подхода: %d)",
            self._search_phase.name, self._approach_clicks,
        )
        self._list_saw_selected = via_list
        if not via_list:
            self._list_cam_scanning = False
            self._list_cam_seen_at = float("-inf")
            self._list_cam_search_started = now
        self._list_cam_how = getattr(self, "_list_cam_how", None)
        if via_list:
            # Клик по списку уже выбрал моба и персонаж бежит к нему. Ctrl+ЛКМ здесь
            # НЕЛЬЗЯ: он выбирает того, кто под прицелом, — а прицел смотрит куда угодно.
            self._last_lock_at = now
            self._target_locked = True
            self._gate_logged = False
        elif clicked:
            # Клик ПКМ подхода уже выбрал моба и запустил бег к нему — это и есть первый удар.
            self._mark_target()
        else:
            if self._USE_WORLD_VISION:
                # Один лишний кадр зрения на переходе — не страшно, это разово.
                getattr(self.vision, "release_bar_lock", lambda: None)()
                aim_info = self._read_world_bar(require_marker=self._COMBAT_REQUIRE_MARKER)
            # Ctrl+ЛКМ -> ПКМ, как только под прицелом не чужой моб (сразу, если так уже).
            # НЕ wait_idle(): FSM-поток не блокируется на очереди ввода.
            self._request_select_clicks(now, "вход в бой по Tab")
        if aim_info.found and not self._list_drives():
            self._maybe_correct_aim(aim_info)
        elif not self._USE_WORLD_VISION:
            # "Только панель": камеру в бою на цель наводит игра (Ctrl+ЛКМ).
            # Наша наводка выключена — гасим её на случай остатка от поиска.
            self.input_manager.clear_aim_target()
        # Новая цель — история HP для детектора смены цели с чистого листа.
        self._swap_samples.clear()
        self._swap_next_sample_at = now
        self._swap_since = None
        # И история для проверки убийства: первая точка — HP при входе.
        self._hp_hist.clear()
        self._hp_hist.append((now, panel_info.hp_percent))
        self._hp_next_sample_at = now + self._KILL_HP_SAMPLE_EVERY_S
        self.state = State.COMBAT
        # Автоатака по ЭТОЙ цели уже запущена кликом выше (или в подходе) —
        # второй раз жать не нужно, пока её не прервёт каст скилла. Если клики
        # выбора ещё ждут прицела (_sel_pending), ПКМ не было — флаг поставит
        # _tick_select_clicks, когда кликнет.
        self._autoattack_engaged = clicked or not self._sel_pending
        # Первая цепочка скиллов — после короткой паузы: персонаж успевает побежать.
        self._next_action_at = now + random.uniform(*self._FIRST_STRIKE_DELAY)

        # Шлагбаум: ротация закрыта до первого упавшего HP цели (см. _ENGAGE_*).
        self._engage_reset(now, panel_info)
        if via_list:
            self._lp_best, self._lp_best_at, self._lp_in_melee = self._list_row.distance_m, now, False
            self._lp_faded_since = None
            self._sprint_on = False
            self._relock_click_at = None
            if getattr(self, "navigator", None) is not None:
                self.navigator.reset_approach()
            if self._list_row.distance_m is not None:
                # Пока расстояние падает, моба не бросаем (_list_progress); старый таймер —
                # только предохранитель на случай, если список перестанет читаться.
                self._eg_deadline = max(self._eg_deadline, now + self._LP_HARD_CAP_S)

        # Режим "Tab по дороге" — только для далёкой цели (выбранной подходом).
        # Ближнюю цель, взятую Tab-ом, дальше "искать поближе" незачем.
        # Выключен константой _ENROUTE_ENABLED (см. комментарий там).
        self._enroute_active = clicked and self._ENROUTE_ENABLED
        if self._enroute_active:
            self._enroute_hp_base = panel_info.hp_percent
            self._enroute_until = now + self._ENROUTE_MAX_S
            self._enroute_next_tab_at = now + random.uniform(*self._ENROUTE_TAB_EVERY_S)
            gamepad_debug_logger.debug(
                "ENROUTE старт: цель далёкая, hp=%.1f%%, Tab раз в %.0f-%.0f с до изменения HP/таймаута %.0f с",
                panel_info.hp_percent, *self._ENROUTE_TAB_EVERY_S, self._ENROUTE_MAX_S,
            )

    def _stop_enroute(self, why: str) -> None:
        self._enroute_active = False
        gamepad_debug_logger.debug("ENROUTE стоп: %s", why)

    def _tick_enroute(self, now: float, panel_info: TargetInfo) -> None:
        """
        COMBAT, режим "Tab по дороге": персонаж бежит к далёкой цели, а мы раз
        в 2-3 с жмём Tab — вдруг по пути есть моб поближе (Tab берёт только
        тех, кто в радиусе таргета, а по мере приближения таких становится
        больше). Один шаг режима = "Tab -> Ctrl+ЛКМ -> ПКМ": как и при
        любом выборе цели, закрепляем её и посылаем персонажа бить.

        Остановка: HP цели на панели изменилось на _ENROUTE_HP_CHANGE_PCT и
        больше (цель получила урон, мы в зоне удара — либо Tab сменил
        цель; в обоих случаях "ловить поближе" больше не нужно) или вышел
        _ENROUTE_MAX_S. Известное ограничение: если Tab сменил цель на
        другого моба с тем же HP (например, оба 100%), бот этого не
        заметит и нажмёт Tab ещё раз — тот может перебрать цели по кругу.
        Поэтому Tab редкий и ограничен по времени.

        Как тестировать без игры: см. fsm_test.py (сценарии K, L) — фейковый
        мир, у которого HP цели меняется в заданный момент.
        """
        if abs(panel_info.hp_percent - self._enroute_hp_base) >= self._ENROUTE_HP_CHANGE_PCT:
            self._stop_enroute(
                "HP цели изменилось %.1f%% -> %.1f%%" % (self._enroute_hp_base, panel_info.hp_percent)
            )
            return
        if now >= self._enroute_until:
            self._stop_enroute("таймаут пробега")
            return
        # is_idle(): не вклиниваем Tab в середину каста цепочки скиллов.
        if now < self._enroute_next_tab_at or not self.input_manager.is_idle():
            return
        if not self._guard_allows(now, "tab"):
            return
        self.input_manager.flick_target(self._SEARCH_FLICK_DIRECTION)
        # После Tab выбранной может оказаться другая цель: старая привязка
        # к её бару не нужна, пусть зрение выберет бар заново.
        getattr(self.vision, "release_bar_lock", lambda: None)()
        self._mark_target()
        self.input_manager.press_button("attack")
        self._autoattack_engaged = True
        self._enroute_next_tab_at = now + random.uniform(*self._ENROUTE_TAB_EVERY_S)
        gamepad_debug_logger.debug("ENROUTE Tab -> Ctrl+ЛКМ -> ПКМ (hp=%.1f%%)", panel_info.hp_percent)

    # --- Шлагбаум "первое упавшее HP" ---

    def _engage_reset(self, now: float, panel_info: "TargetInfo | None" = None) -> None:
        """
        Новая цель (вход в бой или смена цели в бою): шлагбаум закрыт, эталон
        текста HP — тот, что на панели сейчас. Охранник при этом снова разрешает
        смену цели: по новому мобу мы ещё не били.
        """
        pi = panel_info if panel_info is not None else self._last_panel_info
        self._engaged = False
        self._eg_base = pi.hp_text if pi is not None else None
        self._eg_base_hp = pi.hp_percent if pi is not None else 0.0
        self._eg_change_since = None
        self._eg_bar_since = None
        self._eg_entered_at = now
        self._eg_retabs = 0
        # _eg_settle_until НЕ сбрасываем: захват (Ctrl+ЛКМ) при входе ставится раньше
        # этого сброса, и его окно должно действовать.
        self._eg_wait_since = now
        self._eg_gate_logged = False
        self._eg_deadline = now + random.uniform(*self._ENGAGE_RETAB_EVERY_S)
        if self._ENGAGE_GATE_ENABLED:
            gamepad_debug_logger.debug(
                "ENGAGE  шлагбаум закрыт: жду первого падения HP (эталон текста: %s, полоска %.1f%%)",
                self._eg_base, self._eg_base_hp,
            )

    def _update_engagement(self, now: float, panel_info: TargetInfo) -> None:
        """
        Зовётся каждый тик COMBAT, где панель видна. Ищет первое изменение HP цели
        после входа в бой и открывает ротацию (_open_gate). Не нашли за ~5 с —
        Tab -> Ctrl+ЛКМ -> ПКМ (_engage_timeout), и так каждые ~5 с; после
        _ENGAGE_MAX_RETABS подряд бросаем недостижимого моба (_engage_abort).

        Главный сигнал — текст HP (точное число, hp_text.diff_px). Изменение должно
        продержаться _ENGAGE_CONFIRM_S: единичный кадр с отличающимися пикселями
        (вспышка эффекта над панелью) шлагбаум не открывает. Нет текста (None) —
        запасной сигнал: полоска упала на _ENGAGE_BAR_DROP_PCT и держится.

        Как тестировать без игры: fsm_test.py, блок X (фейковая панель с заданным
        текстом HP) и hp_text_test.py (сам текст на реальных кадрах).
        """
        if not self._ENGAGE_GATE_ENABLED:
            return
        if self._engaged:
            self._watch_damage(now, panel_info)
            return
        t = panel_info.hp_text
        if now < self._eg_settle_until:
            # Только что нажали свой Tab: панель могла показать другого моба, его число
            # другое — но это не урон. Пока она "устаканивается", эталон = то, что
            # на ней сейчас (early return: дальше сравнивать не с чем).
            self._eg_base = t
            self._eg_base_hp = panel_info.hp_percent
            self._eg_change_since = None
            self._eg_bar_since = None
            return
        reason = None
        if t is not None:
            if self._eg_base is None:
                self._eg_base = t           # текст появился позже входа — он и есть эталон
            elif hp_text.diff_px(self._eg_base, t) >= self._ENGAGE_TEXT_MIN_PX:
                if self._eg_change_since is None:
                    self._eg_change_since = now
                elif now - self._eg_change_since >= self._ENGAGE_CONFIRM_S:
                    reason = "текст HP изменился на %d px" % hp_text.diff_px(self._eg_base, t)
            else:
                self._eg_change_since = None
        elif self._eg_base_hp - panel_info.hp_percent >= self._ENGAGE_BAR_DROP_PCT:
            if self._eg_bar_since is None:
                self._eg_bar_since = now
            elif now - self._eg_bar_since >= self._ENGAGE_BAR_CONFIRM_S:
                reason = "полоска HP упала %.1f%% -> %.1f%% (текст не читается)" % (
                    self._eg_base_hp, panel_info.hp_percent)
        else:
            self._eg_bar_since = None

        if reason is not None and panel_info.hp_percent > self._eg_base_hp + self._ENGAGE_SWAP_RISE_PCT:
            # Число сменилось, но полоска ВЫРОСЛА — это не урон, а другая цель (лог
            # 13:41:10: 74.8% -> 100%, бот открыл ротацию и бил в полного моба).
            gamepad_debug_logger.debug(
                "ENGAGE  число сменилось, но полоска выросла %.1f%% -> %.1f%% — это другая цель, не урон",
                self._eg_base_hp, panel_info.hp_percent,
            )
            self._lock_new_target(now, "число и полоска выросли %.0f%% -> %.0f%%" % (
                self._eg_base_hp, panel_info.hp_percent))
            return
        if reason is not None:
            # Эталон для сторожа урона (_watch_damage) — число в момент открытия.
            self._eg_dmg_base = t
            self._eg_dmg_base_hp = panel_info.hp_percent
            self._eg_dmg_change_since = None
            self._eg_last_dmg_at = now
            self._eg_retabs = 0
            self._open_gate(now, reason)
        elif now >= self._eg_deadline:
            self._engage_timeout(now)

    def _watch_damage(self, now: float, panel_info: TargetInfo) -> None:
        """
        Сторож урона при ОТКРЫТОЙ ротации. Каждое подтверждённое изменение числа HP =
        урон идёт. Если урона нет _ENGAGED_NO_DAMAGE_S с и цепочка сейчас не идёт
        (долгий каст сам по себе урона может не давать) — шлагбаум закрываем и сразу
        Tab -> Ctrl+ЛКМ -> ПКМ (_engage_timeout), дальше обычный цикл "5 с — Tab".

        Как тестировать без игры: fsm_test.py, блок W2 (фейковое число HP, которое
        после удара перестаёт меняться).
        """
        t = panel_info.hp_text
        hp = panel_info.hp_percent
        if now < self._eg_settle_until:
            # Ctrl+ЛКМ / свой Tab: число на панели может быть чужим — перечитываем эталон.
            self._eg_dmg_base, self._eg_dmg_base_hp = t, hp
            self._eg_dmg_change_since = None
            return
        hit = False
        if t is not None and self._eg_dmg_base is not None:
            if hp_text.diff_px(self._eg_dmg_base, t) >= self._ENGAGE_TEXT_MIN_PX:
                if self._eg_dmg_change_since is None:
                    self._eg_dmg_change_since = now
                elif now - self._eg_dmg_change_since >= self._ENGAGE_CONFIRM_S:
                    hit = True
            else:
                self._eg_dmg_change_since = None
        elif t is not None:
            self._eg_dmg_base = t
        elif self._eg_dmg_base_hp - hp >= self._ENGAGE_BAR_DROP_PCT:
            hit = True                       # текста нет — запасной сигнал по полоске
        if hit:
            self._eg_dmg_base, self._eg_dmg_base_hp = t, hp
            self._eg_dmg_change_since = None
            self._eg_last_dmg_at = now
            return
        quiet = now - self._eg_last_dmg_at
        if quiet < self._ENGAGED_NO_DAMAGE_S or not self.input_manager.is_idle() or self._chain_busy(now):
            return
        if hp < self._NO_DAMAGE_TAB_MIN_HP:
            # Моб РАНЕН — цель не меняем никогда (правило "до смерти"). Только
            # напоминаем персонажу бить: ПКМ, если выбранная под прицелом.
            if self._list_drives() and self._reengage_click(now, "урона нет %.1f с, моб ранен (%.0f%%)" % (quiet, hp)):
                return                            # режим списка: клик по строке надёжнее ПКМ по прицелу
            self._eg_last_dmg_at = now
            clicked = self._crosshair_target() == "marked" or not self._USE_WORLD_VISION
            gamepad_debug_logger.debug(
                "ENGAGE  урона нет %.1f с, моб ранен (%.0f%%) — цель НЕ меняю%s",
                quiet, hp, ", ПКМ по ней" if clicked else ", жду прицела",
            )
            if clicked:
                self.input_manager.press_button("attack")
                self._autoattack_engaged = True
            return
        gamepad_debug_logger.debug(
            "ENGAGE  урона нет %.1f с при открытой ротации — шлагбаум закрываю, ищу цель (Tab)", quiet,
        )
        self._bb_event(now, "no_damage", {"quiet_s": quiet, "hp": hp})
        self._engaged = False
        self._eg_base, self._eg_base_hp = t, hp
        self._eg_change_since = None
        self._eg_bar_since = None
        self._eg_gate_logged = False
        self._eg_wait_since = self._eg_last_dmg_at
        self._engage_timeout(now)

    def _open_gate(self, now: float, reason: str) -> None:
        self._engaged = True
        self._engaged_at = now
        gamepad_debug_logger.debug(
            "ENGAGE  цель в зоне удара через %.1f с после входа (%s) — открываю ротацию",
            now - self._eg_entered_at, reason,
        )
        # Человеческая пауза между "попал" и первым скиллом.
        self._next_action_at = now + random.uniform(*self._ENGAGE_FIRST_SKILL_DELAY)

    def _engage_timeout(self, now: float) -> None:
        """
        HP не менялось ~5 с: Tab -> Ctrl+ЛКМ -> ПКМ, и так каждые ~5 с, пока HP не
        дрогнет. После _ENGAGE_MAX_RETABS подряд — моб недостижим, бросаем бой.

        Как тестировать без игры: fsm_test.py, блок X5 (фейковая панель, HP которой
        не меняется; проверяются интервалы Tab, порядок Tab -> захват -> удар и то,
        что смена числа после своего Tab не открывает шлагбаум).
        """
        if self._eg_retabs >= self._ENGAGE_MAX_RETABS:
            self._engage_abort(now)
            return
        # is_idle(): Tab не вклинивается в середину захвата/удара, ещё стоящих в очереди.
        if not self.input_manager.is_idle():
            return
        # Единый шлюз смены цели. Здесь моб не тронут, и ответ "да"; проверка — чтобы
        # будущая правка не обошла охранника этим путём.
        if not self._guard_allows(now, "tab"):
            self._eg_deadline = now + random.uniform(*self._ENGAGE_RETAB_EVERY_S)
            return
        if self._try_list_switch(now):
            return
        if not self._list_drives() and self._try_vision_switch(now):
            return
        self._eg_retabs += 1
        gamepad_debug_logger.debug(
            "ENGAGE  HP не менялось %.1f с — Tab %d/%d -> ПКМ",
            now - self._eg_wait_since, self._eg_retabs, self._ENGAGE_MAX_RETABS,
        )
        self._bb_event(now, "engage_retab", {"n": self._eg_retabs, "waited_s": now - self._eg_wait_since,
                                             "hp": self._eg_base_hp})
        self._press_tab(now, "HP не менялось — ищу цель ближе")
        # Вердикт TABRES пишет только SEARCH; в бою он не нужен и протух бы к выходу.
        self._tab_pressed_at = None
        # Цель могла смениться: история HP (проверка убийства) и свап-детектор
        # относились к прежней, их эталоны только исказили бы оценку новой.
        self._swap_samples.clear()
        self._swap_next_sample_at = now
        self._swap_since = None
        self._hp_hist.clear()
        self._hp_next_sample_at = now
        if self._USE_WORLD_VISION:
            getattr(self.vision, "release_bar_lock", lambda: None)()
        # Выбрали (Tab) -> закрепили (Ctrl+ЛКМ) -> ударили (ПКМ). Клики — только когда
        # под прицелом не чужой моб (иначе Ctrl+ЛКМ вернул бы прежнюю цель).
        self._request_select_clicks(now, "свой Tab", delay_s=self._SELECT_AFTER_TAB_S)
        self._eg_settle_until = now + self._ENGAGE_RETAB_SETTLE_S
        self._eg_change_since = None
        self._eg_bar_since = None
        self._eg_wait_since = now
        self._eg_deadline = now + random.uniform(*self._ENGAGE_RETAB_EVERY_S)
        self._next_action_at = now + random.uniform(*self._FIRST_STRIKE_DELAY)

    def _engage_abort(self, now: float) -> None:
        """
        Моб недостижим (застрял, за забором, слишком далеко): ротацию не запускали,
        цель не тронута — бросаем её и ищем другую. Первым делом Tab (_handle_search,
        _unreach_tab_pending), иначе панель этого же моба через 0.3 с вернула бы нас в бой.
        """
        waited = now - self._eg_entered_at
        gamepad_debug_logger.debug(
            "STATE   COMBAT -> SEARCH (цель недостижима: HP не менялось %.1f с, Tab-ов %d, ротация не запускалась)",
            waited, self._eg_retabs,
        )
        logger.info("COMBAT -> SEARCH: цель недостижима (HP не менялось %.0f с).", waited)
        self._bb_event(now, "engage_timeout", {"waited_s": waited, "retabs": self._eg_retabs})
        self.state = State.SEARCH
        self._cancel_queue(now)
        self.input_manager.clear_aim_target()
        self.vision.reset_tracking()
        self._target_lost_since = None
        self._reset_search_state(now)
        self._unreach_tab_pending = True
        self._next_action_at = now + random.uniform(*self._POST_KILL_DELAY)

    def _try_vision_switch(self, now: float) -> bool:
        """
        "5 с без урона" при выборе цели зрением: ближний ДРУГОЙ моб в кадре
        (VisionManager.pick_switch_bar) -> выходим в SEARCH/APPROACH, захват зрения
        на него, прицел -> ПКМ. Панель прежней цели до клика не уводит обратно в
        бой (_vision_switch_pending). True — переключились; False — других мобов
        не видно, вызывающий делает запасной Tab.
        """
        if not (self._VISION_TARGETING and self._USE_WORLD_VISION):
            return False
        pick = getattr(self.vision, "pick_switch_bar", None)
        bar = pick() if pick is not None else None
        if bar is None:
            return False
        waited = now - self._eg_wait_since
        gamepad_debug_logger.debug(
            "SWITCH  HP не менялось %.1f с — зрение выбрало ближнего моба (бар x=%d y=%d), бегу к нему",
            waited, bar[0], bar[1],
        )
        self._bb_event(now, "vision_switch", {"waited_s": waited, "bar": list(map(int, bar))})
        self.state = State.SEARCH
        self._cancel_queue(now)
        self._target_lost_since = None
        self._reset_search_state(now)
        self.vision.lock_bar(bar)
        self._vision_switch_pending = True
        self._enter_approach(now, "зрение выбрало ближнего моба")
        return True

    # --- Охранник цели ---

    def _guard_allows(self, now: float, action: str) -> bool:
        """
        Единый шлюз для действий, способных СМЕНИТЬ цель. True — можно.
        Пока моб "занят" (по нему уже били, _engaged), Tab запрещён всегда, а
        одиночный ПКМ по прицелу ('attack_click') разрешён, только если выбранная
        цель сидит под прицелом: тогда ПКМ попадёт в неё, а не в соседа. Если мирового
        зрения нет (режим "только панель"), проверить прицел нечем — разрешаем,
        камеру там ведёт игра (Ctrl+ЛКМ).
        Один шлюз = любой будущий путь смены цели обязан пройти здесь, а не
        "забыть" про правило (идиома: единая точка принятия решения).
        """
        if not self._GUARD_ENABLED or self.state is not State.COMBAT:
            return True
        if action == "attack_click" and self._crosshair_target() == "other":
            # Под прицелом ДРУГОЙ моб: ПКМ выбрал бы его (лог 12:55:49). Неважно, били
            # ли уже текущую цель — клик в чужого всегда смена цели.
            why = "под прицелом другой моб — ПКМ выбрал бы его"
        elif not self._engaged:
            return True
        elif action == "attack_click":
            if not self._USE_WORLD_VISION:
                return True
            ai = self._last_aim_info
            if ai is not None and ai.found and math.hypot(ai.offset_x, ai.offset_y) <= self._GUARD_AIM_TOL_PX:
                return True
            why = "выбранная цель не под прицелом"
        else:
            why = "моб жив и по нему уже били"
        if now >= self._guard_log_at:
            self._guard_log_at = now + self._GUARD_LOG_EVERY_S
            gamepad_debug_logger.debug("GUARD   отказ '%s': %s", action, why)
            self._bb_event(now, "guard_denied", {"action": action, "why": why})
        return False

